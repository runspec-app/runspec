#!/usr/bin/env python3
"""
generate_manifest.py — bake the autonomy manifest for the runspec-fleet plugin.

Connects to `runspec serve` (over SSH for a remote venv, or locally), performs
an MCP initialize + tools/list, and writes autonomy.json into the plugin root.
The manifest maps every served tool to its declared runspec autonomy, read from
the x-autonomy field that `runspec serve` emits on each tool schema.

Usage:
    # Remote venv (the host string works exactly like `runspec jump`):
    python3 scripts/generate_manifest.py --host user@myhost --bin /opt/venvs/fleet/bin/runspec

    # Local venv (for testing — spawns `runspec serve` directly):
    python3 scripts/generate_manifest.py --bin /opt/venvs/fleet/bin/runspec

Regenerate whenever the remote venv's runnables change — the PreToolUse hook
fails closed ("ask") for tools missing from the manifest, so a stale manifest
is inconvenient, never unsafe.

Stdlib only, no runspec install needed on this machine.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

PLUGIN_ROOT = Path(__file__).resolve().parent.parent

INITIALIZE = {
    "jsonrpc": "2.0",
    "id": 1,
    "method": "initialize",
    "params": {
        "protocolVersion": "2024-11-05",
        "capabilities": {},
        "clientInfo": {"name": "runspec-fleet-manifest", "version": "0.1.0"},
    },
}
TOOLS_LIST = {"jsonrpc": "2.0", "id": 2, "method": "tools/list"}


def serve_command(host: str | None, bin_path: str) -> list[str]:
    if host:
        # Mirrors runspec jump: BatchMode because JSON-RPC rides stdin/stdout —
        # an interactive prompt would corrupt the protocol. Everything else
        # (user, port, key, ProxyJump) comes from ~/.ssh/config.
        return ["ssh", "-o", "BatchMode=yes", host, bin_path, "serve"]
    return [bin_path, "serve"]


def mcp_exchange(cmd: list[str], timeout: float) -> tuple[dict[str, Any], dict[str, Any]]:
    """Run initialize + tools/list against a serve process; return both results."""
    payload = json.dumps(INITIALIZE) + "\n" + json.dumps(TOOLS_LIST) + "\n"
    try:
        proc = subprocess.run(
            cmd,
            input=payload,
            capture_output=True,
            text=True,
            timeout=timeout,
        )
    except FileNotFoundError:
        sys.exit(f"✗  command not found: {cmd[0]}")
    except subprocess.TimeoutExpired:
        sys.exit(f"✗  timed out after {timeout:.0f}s waiting for: {' '.join(cmd)}")

    responses: dict[int, dict[str, Any]] = {}
    for line in proc.stdout.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            msg = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(msg.get("id"), int):
            responses[msg["id"]] = msg

    if 1 not in responses or 2 not in responses:
        detail = proc.stderr.strip() or proc.stdout.strip() or f"exit code {proc.returncode}"
        sys.exit(f"✗  no MCP response from `{' '.join(cmd)}`:\n{detail}")

    for rid in (1, 2):
        if "error" in responses[rid]:
            sys.exit(f"✗  MCP error: {responses[rid]['error']}")
    return responses[1]["result"], responses[2]["result"]


def build_manifest(host: str | None, init_result: dict[str, Any], tools_result: dict[str, Any]) -> dict[str, Any]:
    tools: dict[str, Any] = {}
    for tool in tools_result.get("tools", []):
        name = tool.get("name")
        if not name:
            continue
        entry: dict[str, Any] = {"autonomy": tool.get("x-autonomy", "confirm")}
        if tool.get("x-autonomy-reason"):
            entry["reason"] = tool["x-autonomy-reason"]
        # Forward-compatible: pick up per-arg autonomy if/when serve emits it
        # on arg properties (today it does not — see the design doc).
        arg_levels = {
            arg_name: prop["x-autonomy"]
            for arg_name, prop in (tool.get("inputSchema", {}).get("properties") or {}).items()
            if isinstance(prop, dict) and prop.get("x-autonomy")
        }
        if arg_levels:
            entry["args"] = arg_levels
        tools[name] = entry

    return {
        "_comment": "Generated by scripts/generate_manifest.py — do not edit; regenerate when the served runnables change.",
        "host": host or "(local)",
        "server_info": init_result.get("serverInfo", {}),
        "tools": tools,
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--host", help="SSH host string (user@host); omit to spawn serve locally")
    ap.add_argument("--bin", default="runspec", help="remote runspec executable (default: runspec on PATH)")
    ap.add_argument("--out", type=Path, default=PLUGIN_ROOT / "autonomy.json", help="output path (default: plugin root)")
    ap.add_argument("--timeout", type=float, default=30.0, help="seconds to wait for serve (default: 30)")
    args = ap.parse_args()

    cmd = serve_command(args.host, args.bin)
    init_result, tools_result = mcp_exchange(cmd, args.timeout)
    manifest = build_manifest(args.host, init_result, tools_result)

    args.out.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    counts: dict[str, int] = {}
    for entry in manifest["tools"].values():
        counts[entry["autonomy"]] = counts.get(entry["autonomy"], 0) + 1
    summary = ", ".join(f"{n} {level}" for level, n in sorted(counts.items())) or "none"
    server = manifest["server_info"].get("name", "?")
    print(f"✓  {len(manifest['tools'])} tool(s) from '{server}' → {args.out}  ({summary})")


if __name__ == "__main__":
    main()
