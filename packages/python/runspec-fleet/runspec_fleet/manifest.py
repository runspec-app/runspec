"""
manifest.py — write the autonomy manifest the PreToolUse hook reads.

The gateway rewrites this file on every discovery change, so the hook is always
fresh with no manual generation step. Shape matches the existing
``autonomy_gate.py`` hook (``examples/claude-code-plugin``): a ``tools`` map from
the namespaced tool name to its autonomy level, optional reason, and per-arg
escalation levels.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .catalog import Tool

_COMMENT = "Generated by runspec-fleet on every discovery — do not edit; it is rewritten automatically."


def build_manifest(tools: list[Tool], server_name: str = "fleet") -> dict[str, Any]:
    entry_tools: dict[str, Any] = {}
    for t in tools:
        entry: dict[str, Any] = {"autonomy": t.autonomy}
        reason = t.schema.get("x-autonomy-reason")
        if reason:
            entry["reason"] = reason
        props = (t.schema.get("inputSchema") or {}).get("properties") or {}
        arg_levels = {name: prop["x-autonomy"] for name, prop in props.items() if isinstance(prop, dict) and prop.get("x-autonomy")}
        if arg_levels:
            entry["args"] = arg_levels
        entry_tools[t.name] = entry
    return {
        "_comment": _COMMENT,
        "server_info": {"name": server_name},
        "tools": entry_tools,
    }


def write_manifest(path: Path, tools: list[Tool], server_name: str = "fleet") -> None:
    manifest = build_manifest(tools, server_name)
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(path.suffix + ".tmp")
        tmp.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        tmp.replace(path)
    except OSError:
        # Best-effort: a manifest we can't write degrades the hook to "ask",
        # never to "allow" — safe to swallow.
        pass
