"""
docsgen.py — a deterministic markdown runbook wiki from runbooks + hosts.

Runbooks (``runspec_runbooks.toml``) are written for the *agent* (step templates that
name runnables). This renders them as a human-followable **wiki** so that during
an outage — when the console itself may be down — a person can SSH to the host and
run the same runspec runnables the agent would have.

``render_wiki(runbooks, hosts, runnables) -> {relpath: markdown}`` is **pure** and
**deterministic**: same inputs → byte-identical markdown out (everything sorted,
no timestamps), so the generated files diff cleanly when committed back to the
config repo and a daily regenerate is a no-op unless the config actually changed.

Output:
  * ``README.md``         — index: an outage preamble + links to the sections below
  * ``runbooks/<id>.md``    — one page per runbook: when-to-use, steps, params, cross-links
  * ``hosts.md``          — hosts → ssh target → runnable count → referencing runbooks
  * ``runnables.md``      — catalogue index, linking each host's runnable page
  * ``runnables/<host>.md`` — every runnable on a host: description, autonomy,
    run-as, args, and subcommands (the "what can I run and how" for an outage)
  * ``maintaining-docs.md`` — how to regenerate, + the default "regenerate" runbook as
    paste-able TOML so an uploader can add it to the repo's ``runspec_runbooks.toml``

Runbooks are what ``memory.load_runbooks`` returns
(``id``/``title``/``symptom``/``steps``/``tags``/``args``); hosts are fleet entries
(``name``/``ssh``/``tags``); runnables are the console's cached discovery catalogue
(``bridge.get_runnables("all")`` — ``name``/``host``/``group``/``description``/
``args``/``autonomy``/``commands`` …), so the catalogue publishes offline from the
last sync, no live SSH needed.
"""

from __future__ import annotations

import re
from typing import Any

# host__runnable tool tokens an agent would call, spotted in a runbook's free-text
# steps so the wiki can cross-link them (deterministic given the steps text).
_RUNNABLE_TOKEN = re.compile(r"\b[A-Za-z0-9][\w-]*__[A-Za-z0-9][\w-]*\b")
_UNSAFE = re.compile(r"[^a-z0-9_-]+")

# The self-service "regenerate the docs" runbook. It isn't installed anywhere by
# this module — instead its ready-to-paste TOML is written into the wiki
# (maintaining-docs.md) so whoever uploads the docs can drop it into the repo's
# runspec_runbooks.toml; from there it rides Config Sync to the whole team and shows
# up in each console's `$` menu. (Kept as a plain dict so the page renders it both
# as TOML and as a normal runbook page.)
DEFAULT_RUNBOOK: dict[str, Any] = {
    "id": "regenerate-runbook-docs",
    "title": "Regenerate the runbook docs",
    "symptom": "The runbook wiki is missing or stale after runbooks or hosts changed",
    # An ordered ``[[runbook.step]]`` array — the readable, diffable form (so the
    # paste-able example in the wiki also teaches the current format).
    "step": [
        {
            "text": (
                "These human-readable runbooks are generated by runspec-console from "
                "the team's runbooks + fleet. Open the console, then Settings -> "
                "Config Sync -> Runbook docs."
            )
        },
        {
            "text": (
                "Set the output directory to your local clone of this config repo "
                "(the folder these docs live in)."
            )
        },
        {"text": "Click Generate."},
        {
            "text": (
                "Review the changes, then commit and push them so the team gets the "
                "update on their next Config Sync pull. The output is deterministic, "
                "so re-running only changes what the runbooks actually changed."
            )
        },
    ],
    "tags": ["docs", "self-service"],
}


def render_wiki(
    runbooks: list[dict[str, Any]],
    hosts: list[dict[str, Any]],
    runnables: list[dict[str, Any]] | None = None,
) -> dict[str, str]:
    """Render the whole wiki as ``{relative_path: markdown_text}``."""
    runbooks = sorted(
        (s for s in runbooks if s.get("id")), key=lambda s: str(s.get("id"))
    )
    host_names = sorted({str(h.get("name")) for h in hosts if h.get("name")})
    runnables = list(runnables or [])

    # Runnables grouped by host (so each host gets its own catalogue page).
    by_host: dict[str, list[dict[str, Any]]] = {}
    for r in runnables:
        host = str(r.get("host") or "")
        if r.get("name"):
            by_host.setdefault(host, []).append(r)

    out: dict[str, str] = {"README.md": _render_index(runbooks, host_names, by_host)}
    for runbook in runbooks:
        out[f"runbooks/{_safe(str(runbook['id']))}.md"] = _render_runbook(
            runbook, host_names
        )
    out["hosts.md"] = _render_hosts(hosts, runbooks, by_host)
    out["runnables.md"] = _render_runnables_index(host_names, by_host)
    for host, rs in by_host.items():
        out[f"runnables/{_safe(host)}.md"] = _render_host_runnables(host, rs)
    out["maintaining-docs.md"] = _render_maintaining()
    return out


# ── pages ─────────────────────────────────────────────────────────────────────


def _render_index(
    runbooks: list[dict[str, Any]],
    host_names: list[str],
    by_host: dict[str, list[dict[str, Any]]],
) -> str:
    lines = [
        "# Runbook wiki",
        "",
        "Human-followable docs generated from the console's configuration. **If the "
        "console is unavailable**, pick the runbook for your situation below, then "
        "SSH to the relevant host and run the runspec runnable its steps name — the "
        "same one the agent would have run:",
        "",
        "```",
        "ssh <host>            # see hosts.md for the SSH target",
        "runspec local         # list the runnables available on that host",
        "runspec run <runnable> --help",
        "```",
        "",
        "## Runbooks by tag",
        "",
    ]
    by_tag: dict[str, list[dict[str, Any]]] = {}
    for runbook in runbooks:
        tags = [str(t).strip() for t in (runbook.get("tags") or []) if str(t).strip()]
        for tag in tags or ["Untagged"]:
            by_tag.setdefault(tag, []).append(runbook)

    if not runbooks:
        lines.append("_No runbooks defined yet._")
    for tag in sorted(by_tag, key=lambda t: (t == "Untagged", t.lower())):
        lines.append(f"### {tag}")
        lines.append("")
        for runbook in by_tag[tag]:
            sid = _safe(str(runbook["id"]))
            title = str(runbook.get("title") or runbook["id"])
            symptom = str(runbook.get("symptom") or "").strip()
            suffix = f" — {symptom}" if symptom else ""
            lines.append(f"- [{title}](runbooks/{sid}.md){suffix}")
        lines.append("")

    lines.append("## Runnables")
    lines.append("")
    total = sum(len(rs) for rs in by_host.values())
    if total:
        lines.append(
            f"{total} runnable(s) across {len(by_host)} host(s) — the catalogue of "
            "everything you can run, with its arguments. See "
            "[runnables.md](runnables.md)."
        )
    else:
        lines.append(
            "_No runnables discovered yet — connect to a host in the console first, "
            "then regenerate._"
        )
    lines.append("")
    lines.append("## Hosts")
    lines.append("")
    if host_names:
        lines.append(f"{len(host_names)} host(s) — see [hosts.md](hosts.md).")
    else:
        lines.append("_No hosts defined._")
    lines.append("")
    lines.append("## Maintaining these docs")
    lines.append("")
    lines.append(
        "These pages are generated — don't hand-edit them. See "
        "[maintaining-docs.md](maintaining-docs.md) for how to regenerate them and "
        "a ready-to-paste runbook that puts a one-click refresh in everyone's console."
    )
    lines.append("")
    return "\n".join(lines)


def _render_runbook(runbook: dict[str, Any], host_names: list[str]) -> str:
    title = str(runbook.get("title") or runbook["id"])
    lines = [f"# {title}", ""]

    symptom = str(runbook.get("symptom") or "").strip()
    if symptom:
        lines += [f"**When to use:** {symptom}", ""]

    tags = sorted(
        {str(t).strip() for t in (runbook.get("tags") or []) if str(t).strip()}
    )
    if tags:
        lines += ["**Tags:** " + ", ".join(f"`{t}`" for t in tags), ""]

    steps = _runbook_prose(runbook)
    lines += ["## Steps", "", steps or "_No steps recorded._", ""]

    params = _params_table(runbook.get("args"))
    if params:
        lines += ["## Parameters", "", *params, ""]

    refs_runnables = sorted(set(_RUNNABLE_TOKEN.findall(steps)))
    if refs_runnables:
        lines += ["## Runnables referenced", ""]
        lines += [f"- `{r}`" for r in refs_runnables]
        lines.append("")

    refs_hosts = _referenced_hosts(steps, host_names)
    if refs_hosts:
        lines += ["## Hosts referenced", ""]
        lines += [f"- [`{h}`](../hosts.md)" for h in refs_hosts]
        lines.append("")

    return "\n".join(lines)


def _render_hosts(
    hosts: list[dict[str, Any]],
    runbooks: list[dict[str, Any]],
    by_host: dict[str, list[dict[str, Any]]],
) -> str:
    lines = ["# Hosts", ""]
    rows = sorted(
        ((str(h.get("name")), h) for h in hosts if h.get("name")),
        key=lambda r: r[0],
    )
    if not rows:
        return "# Hosts\n\n_No hosts defined._\n"

    # Reverse map: host name → runbooks whose steps reference it.
    used_by: dict[str, list[str]] = {}
    for runbook in runbooks:
        steps = _runbook_prose(runbook)
        for name in _referenced_hosts(steps, [n for n, _ in rows]):
            used_by.setdefault(name, []).append(
                str(runbook.get("title") or runbook["id"])
            )

    lines += [
        "| Host | SSH target | Tags | Runnables | Used by runbooks |",
        "|---|---|---|---|---|",
    ]
    for name, h in rows:
        ssh = _cell(str(h.get("ssh") or ""))
        tags = ", ".join(
            str(t).strip() for t in (h.get("tags") or []) if str(t).strip()
        )
        count = len(by_host.get(name, []))
        runnables = f"[{count}](runnables/{_safe(name)}.md)" if count else "—"
        runbooks = ", ".join(sorted(used_by.get(name, []))) or "—"
        lines.append(
            f"| `{name}` | {ssh or '—'} | {_cell(tags) or '—'} | {runnables} | {_cell(runbooks)} |"
        )
    lines.append("")
    return "\n".join(lines)


def _render_runnables_index(
    host_names: list[str], by_host: dict[str, list[dict[str, Any]]]
) -> str:
    """The catalogue index: each host links to its per-host runnable page."""
    lines = [
        "# Runnables",
        "",
        "Everything the fleet can run, as discovered by the console — the same "
        "runnables the agent invokes. During an outage, SSH to the host and run "
        "these directly. Pages are per host:",
        "",
    ]
    hosts_with = sorted(h for h in by_host if by_host.get(h))
    if not hosts_with:
        lines.append(
            "_No runnables discovered yet — connect to a host in the console, then "
            "regenerate._"
        )
        lines.append("")
        return "\n".join(lines)
    for host in hosts_with:
        rs = by_host[host]
        lines.append(
            f"- [`{host}`](runnables/{_safe(host)}.md) — {len(rs)} runnable(s)"
        )
    lines.append("")
    return "\n".join(lines)


def _render_host_runnables(host: str, runnables: list[dict[str, Any]]) -> str:
    """One host's full catalogue: each runnable's description, autonomy, args, and
    subcommands."""
    lines = [f"# Runnables on `{host}`", ""]
    lines.append(
        "Run these on the host (in the runnable's runspec venv); the agent runs "
        "the same ones. Arguments below are what each accepts."
    )
    lines.append("")
    for r in sorted(
        runnables, key=lambda r: (str(r.get("group") or ""), str(r.get("name")))
    ):
        lines += _render_one_runnable(r, level=2)
    return "\n".join(lines)


def _render_one_runnable(r: dict[str, Any], level: int) -> list[str]:
    """A single runnable (recursing into subcommands), as markdown lines."""
    hashes = "#" * level
    name = str(r.get("name") or "")
    group = str(r.get("group") or "").strip()
    heading = f"{hashes} `{name}`" + (f"  ·  _{group}_" if group else "")
    lines = [heading, ""]

    desc = str(r.get("description") or "").strip()
    if desc:
        lines += [desc, ""]

    meta = [f"**Autonomy:** {r.get('autonomy') or 'confirm'}"]
    if r.get("runAs"):
        meta.append(f"**Runs as:** `{r['runAs']}`")
    if r.get("requireCommand"):
        meta.append("**Requires a subcommand**")
    lines += [" · ".join(meta), ""]

    table = _args_table(r.get("args") or [])
    if table:
        lines += [*table, ""]

    commands = r.get("commands")
    if isinstance(commands, dict) and commands:
        lines += [f"{'#' * (level + 1)} Subcommands of `{name}`", ""]
        for sub_name in sorted(commands):
            sub = commands[sub_name]
            if isinstance(sub, dict):
                lines += _render_one_runnable(sub, level + 2)
    return lines


def _render_maintaining() -> str:
    """The 'how these docs are made' page, carrying the default runbook as paste-able
    TOML so an uploader can add it to the repo's ``runspec_runbooks.toml``."""
    return "\n".join(
        [
            "# Maintaining these docs",
            "",
            "These runbooks are generated by **runspec-console** from the team's "
            "runbooks (`runspec_runbooks.toml`) and fleet (`runspec_hosts.toml`) — so "
            "they always reflect what the agent would actually do. Don't hand-edit "
            "the generated pages; change the runbooks instead and regenerate.",
            "",
            "## Add a one-click 'regenerate' runbook",
            "",
            "Paste the block below into this repo's `runspec_runbooks.toml` and commit "
            "it. After the next Config Sync pull it appears in every console's `$` "
            "menu, so anyone can regenerate and re-commit the docs:",
            "",
            "```toml",
            _runbook_to_toml(DEFAULT_RUNBOOK).rstrip(),
            "```",
            "",
            "### What it says",
            "",
            _runbook_prose(DEFAULT_RUNBOOK),
            "",
        ]
    )


# ── helpers ─────────────────────────────────────────────────────────────────────


def _runbook_prose(runbook: dict[str, Any]) -> str:
    """A runbook's body as the numbered prose the agent follows — from the structured
    ``[[runbook.step]]`` array or a legacy ``steps`` string, via ``memory.render_runbook``
    (pure; unfilled ``{{placeholders}}`` stay intact so token/host cross-linking still
    sees them). Keeps docsgen deterministic — no I/O in the render path."""
    from . import memory

    return memory.render_runbook(runbook, {}).strip()


def _runbook_to_toml(runbook: dict[str, Any]) -> str:
    """Render one runbook as a ``[[runbook]]`` TOML block (deterministic, valid TOML).

    Emits the ordered ``[[runbook.step]]`` array when the runbook has one, else the
    legacy ``steps`` string — so the paste-able wiki example models the current format."""
    import tomli_w

    entry: dict[str, Any] = {
        "id": runbook["id"],
        "title": runbook.get("title", ""),
        "symptom": runbook.get("symptom", ""),
        "tags": list(runbook.get("tags") or []),
    }
    step = runbook.get("step")
    if isinstance(step, list) and step:
        entry["step"] = [dict(s) for s in step if isinstance(s, dict)]
    else:
        entry["steps"] = runbook.get("steps", "")
    if runbook.get("args"):
        entry["args"] = dict(runbook["args"])
    return tomli_w.dumps({"runbook": [entry]}, multiline_strings=True)


def _params_table(args_table: dict[str, Any] | None) -> list[str]:
    """A runbook's ``[runbook.args]`` rendered as a markdown table (or [] when none)."""
    if not args_table:
        return []
    from .runbookargs import parse_runbook_args

    return _args_table(parse_runbook_args(args_table))


def _args_table(defs: list[dict[str, Any]]) -> list[str]:
    """A list of ArgDef dicts (runbook params or a runnable's args — same shape from
    ``discovery._build_args``) → a markdown table (or [] when there are none)."""
    if not defs:
        return []
    rows = [
        "| Name | Type | Required | Default | Description |",
        "|---|---|---|---|---|",
    ]
    for d in defs:
        name = _cell(str(d.get("name", "")))
        typ = _cell(str(d.get("type", "")))
        if d.get("options"):
            typ += " (" + ", ".join(str(o) for o in d["options"]) + ")"
        required = "yes" if d.get("required") else "no"
        default = "" if d.get("default") is None else str(d.get("default"))
        desc = _cell(str(d.get("description", "")))
        rows.append(
            f"| `{name}` | {_cell(typ)} | {required} | {_cell(default) or '—'} | {desc or '—'} |"
        )
    return rows


def _referenced_hosts(steps: str, host_names: list[str]) -> list[str]:
    """Host names that appear as whole words in ``steps`` (sorted, deduped)."""
    found = []
    for name in sorted(set(host_names)):
        if re.search(rf"(?<![\w-]){re.escape(name)}(?![\w-])", steps):
            found.append(name)
    return found


def _cell(text: str) -> str:
    """Escape a value for a markdown table cell (pipes, newlines)."""
    return text.replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ").strip()


def _safe(runbook_id: str) -> str:
    """A filesystem-safe slug for a runbook id (ids are already slugs; belt + braces)."""
    return _UNSAFE.sub("-", runbook_id.lower()).strip("-") or "runbook"
