def _parse_ts(ts: Any) -> datetime | None:
    s = str(ts or "").strip()
    if not s:
        return None
    try:
        dt = datetime.fromisoformat(s.replace("Z", "+00:00"))
    except ValueError:
        return None
    return dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)


# Arg names whose value says who ran it rather than how a runnable is used — a
# username, an email, a run-as account. Those differ per person, so a habit
# built on one ("search is usually run with username = jason") is only true for
# whoever ran it and would be wrong in the team wiki.
_PERSONAL_ARG_WORDS = frozenset(
    {
        "user",
        "username",
        "userid",
        "uid",
        "login",
        "email",
        "mail",
        "upn",
        "owner",
        "account",
        "principal",
        "author",
        "assignee",
        "reporter",
        "runas",
    }
)


def _bare_account(v: str) -> str:
    """``DOMAIN\\jason`` / ``jason@corp.com`` / ``Jason`` → ``jason``."""
    v = v.strip().lower().rsplit("\\", 1)[-1]
    return v.split("@", 1)[0]


def _personal_arg(name: str, value: str, run: dict[str, Any]) -> bool:
    """True when ``name = value`` describes the person running, not the run: the
    arg is named like a user/account field, or its value is the operator's or
    run-as account."""
    norm = name.lower().replace("-", "_")
    words = {w for w in norm.split("_") if w}
    if words & _PERSONAL_ARG_WORDS or norm.replace("_", "") in _PERSONAL_ARG_WORDS:
        return True
    bare = _bare_account(value)
    if not bare:
        return False
    people = {
        _bare_account(str(run.get(k) or "")) for k in ("operator", "runAs", "user")
    }
    return bare in people - {""}


def _looks_like_path(v: str) -> bool:
    return (
        bool(re.match(r"^(/[^\s]+|[A-Za-z]:[\\/][^\n]*|~/[^\s]+)$", v)) and len(v) > 2
    )


def _runnable_label(row: dict[str, Any]) -> str:
    name = str(row.get("runnable") or "").strip()
    path = [str(p) for p in (row.get("commandPath") or []) if str(p).strip()]
    return " ".join([name, *path]) if path else name


def _arg_key(name: str) -> str:
    return str(name).strip().lstrip("-").replace("-", "_").lower()


def _value_str(v: Any) -> str:
    return ", ".join(map(str, v)) if isinstance(v, list) else str(v)


def arg_defaults(records: list[dict[str, Any]]) -> dict[str, dict[str, set[str]]]:
    """Each runnable's declared arg defaults, from discovered runnable records
    (``_runnables_cache`` shape), keyed like ``_runnable_label``: ``name`` for
    the top level and ``name sub …`` for each subcommand (which inherits its
    parents' args). Values are stringified as ``observe`` stringifies history
    args; a runnable found in several venvs keeps every default it declares."""
    out: dict[str, dict[str, set[str]]] = defaultdict(lambda: defaultdict(set))

    def walk(node: dict[str, Any], label: str, inherited: dict[str, set[str]]) -> None:
        mine = {k: set(v) for k, v in inherited.items()}
        for a in node.get("args") or []:
            if not isinstance(a, dict) or not a.get("name") or "default" not in a:
                continue
            d = a.get("default")
            if d is None:
                continue
            mine.setdefault(_arg_key(a["name"]), set()).add(_value_str(d))
        for k, vals in mine.items():
            out[label][k] |= vals
        for seg, sub in (node.get("commands") or {}).items():
            if isinstance(sub, dict):
                walk(sub, f"{label} {seg}", mine)

    for r in records or []:
        if isinstance(r, dict) and r.get("name"):
            walk(r, str(r["name"]), {})
    return {k: dict(v) for k, v in out.items()}


def observe(
    history: list[dict[str, Any]],
    *,
    defaults: dict[str, dict[str, set[str]]] | None = None,
    min_runs: int = MIN_RUNS,
    habit_share: float = HABIT_SHARE,
    pair_window_s: int = PAIR_WINDOW_S,
) -> list[dict[str, Any]]:
    """Mine run-history rows (``get_history_all`` shape) into ``observed`` facts:

    * **arg habits** — a runnable is usually run with ``arg=value`` (a value seen
      in ≥ ``habit_share`` of its runs, at least ``min_runs`` times); path values
      also link a ``file:`` entity. Args that name the person running (a
      username, email or run-as account, or a value equal to the operator) are
      skipped: they differ per person, so they are never a team fact. So
      are args left at the runnable's declared default (``defaults``, from
      ``arg_defaults``) — "usually run with format = 'json'" when json is the
      default says nothing,
    * **pairings** — runnable B is often run after A by the same operator within
      ``pair_window_s`` (≥ ``min_runs`` times).

    Which runnable runs on which host is deliberately *not* a fact: History,
    ``search_history`` and discovery already answer it, and as facts it buried
    the wiki in "X is used on H" rows.

    Deterministic: same history → same facts (ids are content hashes)."""
    rows = [
        r
        for r in history
        if str(r.get("runnable") or "").strip()
        and r.get("kind") in (None, "", "runnable")
        and str(r.get("runnable")) != "chat"
    ]
    facts: list[dict[str, Any]] = []

    def add(
        kind: str, about: list[str], text: str, n: int, runs: list[dict[str, Any]]
    ) -> None:
        stamps = sorted(str(r.get("ts") or "")[:10] for r in runs if r.get("ts"))
        evidence = [
            f"run:{r.get('runId') or r.get('id')}"
            for r in runs[-5:]
            if r.get("runId") or r.get("id")
        ]
        try:
            facts.append(
                make_fact(
                    kind=kind,
                    about=about,
                    text=text,
                    status="observed",
                    source="capture",
                    author="",
                    evidence=evidence,
                    confirmations=n,
                    first_seen=stamps[0] if stamps else "",
                    last_confirmed=stamps[-1] if stamps else "",
                )
            )
        except ValueError:
            pass  # e.g. a value that looks like a secret — never stored

    by_runnable: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for r in rows:
        by_runnable[_runnable_label(r)].append(r)

    for label, runs in sorted(by_runnable.items()):
        base = str(runs[0].get("runnable"))
        n = len(runs)
        declared = (defaults or {}).get(label) or {}
        # arg habits
        if n >= min_runs:
            values: dict[tuple[str, str], list[dict[str, Any]]] = defaultdict(list)
            for r in runs:
                args = r.get("args") or {}
                if not isinstance(args, dict):
                    continue
                for k, v in args.items():
                    if v is None or v is False or v == "" or v == []:
                        continue
                    sv = _value_str(v)
                    if len(sv) > MAX_VALUE_LEN:
                        continue
                    if sv in declared.get(_arg_key(str(k)), ()):
                        continue  # unchanged default — not a habit
                    if _personal_arg(str(k), sv, r):
                        continue  # per-person, never a team fact
                    values[(str(k), sv)].append(r)
            for (k, sv), vruns in sorted(values.items()):
                c = len(vruns)
                if c >= min_runs and c / n >= habit_share:
                    about = [f"runnable:{base}"]
                    if _looks_like_path(sv):
                        about.append(f"file:{sv}")
                    shown = "on" if sv == "True" else repr(sv)
                    add(
                        "arg-habit",
                        about,
                        f"{label} is usually run with {k} = {shown} ({c} of {n} runs).",
                        c,
                        vruns,
                    )

    # pairings: consecutive runs by the same operator inside the window
    seq = sorted(
        ((t, r) for r in rows if (t := _parse_ts(r.get("ts"))) is not None),
        key=lambda p: p[0],
    )
    last_by_op: dict[str, tuple[datetime, dict[str, Any]]] = {}
    pairs: dict[tuple[str, str], list[dict[str, Any]]] = defaultdict(list)
    for t, r in seq:
        op = str(r.get("operator") or "").strip()
        prev = last_by_op.get(op)
        if prev is not None:
            pt, pr = prev
            a, b = str(pr.get("runnable")), str(r.get("runnable"))
            if a != b and (t - pt).total_seconds() <= pair_window_s:
                pairs[(a, b)].append(r)
        last_by_op[op] = (t, r)
    for (a, b), pruns in sorted(pairs.items()):
        if len(pruns) >= min_runs:
            add(
                "pairing",
                [f"runnable:{a}", f"runnable:{b}"],
                f"{b} is often run after {a} ({len(pruns)} times).",
                len(pruns),
                pruns,
            )
    # A content-hash id can repeat (same text) — keep the first.
    seen: set[str] = set()
    out = []
    for f in facts:
        if f["id"] not in seen:
            seen.add(f["id"])
            out.append(f)
    return out


# ── linking facts to the fleet's real entities ──────────────────────────────

#: Entity types whose names are matched against a fact's text and against the
#: model's guesses, so a fact joins the existing node instead of floating alone.
LINKABLE_TYPES = (
    "host",
    "group",
    "profile",
    "runnable",
    "trigger",
    "schedule",
    "runbook",
)
#: Names too common to treat a bare mention in prose as a reference (they are
#: still linked when the fact names them as a subject).
_COMMON_NAMES = frozenset(
    {"local", "default", "all", "test", "main", "prod", "dev", "uat", "staging", "data"}
)
MAX_ABOUT = 8


def _name_key(name: str) -> str:
    """Spelling-insensitive key: ``"Linux Servers"`` == ``linux-servers``."""
    return "".join(_WORD.findall(str(name).lower()))


def entity_catalog(entities: Iterable[str]) -> dict[str, list[str]]:
    """``name key -> [refs]`` for the known entities (``type:name``), so a guess
    like ``term:Linux Servers`` resolves to ``group:Linux Servers``."""
    cat: dict[str, list[str]] = defaultdict(list)
    for ref in entities:
        ref = normalize_entity(ref)
        if not ref or entity_type(ref) not in LINKABLE_TYPES:
            continue
        key = _name_key(entity_name(ref))
        if key and ref not in cat[key]:
            cat[key].append(ref)
    return dict(cat)


def _resolve(ref: str, catalog: dict[str, list[str]]) -> str:
    kind = entity_type(ref)
    if kind == "file":
        return ref
    hits = catalog.get(_name_key(entity_name(ref)), [])
    if not hits:
        return ref
    same = [h for h in hits if entity_type(h) == kind]
    if same:
        return same[0]  # same type, canonical spelling
    return hits[0] if len(hits) == 1 else ref  # ambiguous across types: keep


def link_about(
    about: Iterable[str], text: str, catalog: dict[str, list[str]]
) -> list[str]:
    """A fact's subjects joined up with the fleet: each guessed ref resolved to
    the known entity of that name (any type, canonical spelling), plus every
    known host / group / profile / runnable / trigger / schedule / runbook the
    text names. Capped at :data:`MAX_ABOUT` subjects (named ones first)."""
    refs = [_resolve(r, catalog) for r in (normalize_entity(a) for a in about) if r]
    seen = set(refs)
    if catalog and text:
        low = f" {' '.join(_WORD.findall(text.lower()))} "
        names: list[tuple[str, str]] = []
        for hits in catalog.values():
            for h in hits:
                names.append((entity_name(h), h))
        # Longest names first, so "web-01-backup" wins over "web-01".
        for name, ref in sorted(names, key=lambda p: -len(p[0])):
            if ref in seen or len(refs) >= MAX_ABOUT:
                continue
            words = " ".join(_WORD.findall(name.lower()))
            if len(words) < 3 or words in _COMMON_NAMES:
                continue
            if f" {words} " in low:
                refs.append(ref)
                seen.add(ref)
                # Consume the match so "web-01" doesn't also hit inside
                # "web-01-backup".
                low = low.replace(f" {words} ", "  ")
    out: list[str] = []
    for r in refs:
        if r not in out:
            out.append(r)
    return out[:MAX_ABOUT]


# ── the older agent memory (runspec_memory.toml) ──────────────────────────────


def memory_to_facts(
    rows: Iterable[dict[str, Any]],
    *,
    author: str = "",
    link: Any = None,
    max_pins: int = PIN_MAX,
) -> tuple[list[dict[str, Any]], list[str], list[str]]:
    """Turn the older memory store's entries (``remember`` facts: ``app`` /
    ``fact`` / ``tags`` / ``pinned`` / ``hits``) into **pending** wiki facts.

    They land in the review inbox rather than straight in the wiki because the
    old memory was machine-local by design and approved wiki facts are what
    Memory Sync shares — the operator decides which become team knowledge.

    Subjects: ``app:<app>`` (unless it was the default ``general``) and up to
    three tags as ``topic:<tag>``, then ``link(about, text)`` (e.g.
    :func:`link_about` against the fleet) joins them to known entities; a fact
    with no subject at all is about ``topic:general``. The memory id goes in
    ``evidence``. A fact that now looks like it carries a secret is skipped.

    Returns ``(facts, pin_ids, skipped_memory_ids)``; ``pin_ids`` are the facts
    that were pinned, most-recalled first, at most ``max_pins``."""
    facts: dict[str, dict[str, Any]] = {}
    pinned: list[tuple[int, str]] = []
    skipped: list[str] = []
    for row in rows:
        text = str(row.get("fact") or "").strip()
        mid = str(row.get("id") or "")
        if not text:
            continue
        app = str(row.get("app") or "general").strip() or "general"
        about = [] if app == "general" else [f"app:{app}"]
        about += [
            f"topic:{t}" for t in list(row.get("tags") or [])[:3] if str(t).strip()
        ]
        if link is not None:
            about = list(link(about, text))
        if not about:
            about = ["topic:general"]
        created = str(row.get("created") or "")[:10]
        try:
            fact = make_fact(
                kind="note",
                about=about,
                text=text,
                status="pending",
                source="memory",
                author=author,
                evidence=[mid] if mid else [],
                first_seen=created,
            )
        except ValueError:
            skipped.append(mid)
            continue
        facts.setdefault(fact["id"], fact)
        if row.get("pinned"):
            pinned.append((int(row.get("hits", 0) or 0), fact["id"]))
    pinned.sort(key=lambda p: p[0], reverse=True)
    pins: list[str] = []
    for _hits, fid in pinned:
        if fid not in pins and len(pins) < max_pins:
            pins.append(fid)
    return list(facts.values()), pins, skipped


# ── facts read from the console's own config (no AI) ────────────────────────


def _split_run(run: str) -> tuple[list[str], str]:
    """A trigger ``run`` target → (target refs, runnable). ``group:G__r`` → a
    group, ``host__r`` → a host, a bare ``r`` → no target."""
    run = str(run or "").strip()
    if "__" not in run:
        return [], run
    target, _, runnable = run.rpartition("__")
    if target.startswith("group:"):
        return [f"group:{target[6:]}"], runnable
    return [f"host:{target}"], runnable


def _join(names: list[str], limit: int = 12) -> str:
    shown = names[:limit]
    more = len(names) - len(shown)
    return ", ".join(shown) + (f" and {more} more" if more > 0 else "")


def observe_config(
    *,
    hosts: Iterable[dict[str, Any]] = (),
    triggers: Iterable[dict[str, Any]] = (),
    schedules: Iterable[dict[str, Any]] = (),
    runbooks: Iterable[dict[str, Any]] = (),
    filters: Iterable[dict[str, Any]] = (),
    catalog: dict[str, list[str]] | None = None,
) -> list[dict[str, Any]]:
    """Facts read straight from the console's config (``status = observed``,
    ``source = config``) so the wiki — and the graph — know how the automation
    is set up: what each trigger and schedule runs where, what each runbook is
    for and which runnables it uses, and the saved file-relay filters. Rebuilt
    on every capture, so it never goes stale; the *why* behind the setup is what
    operators and chats add.

    Group and profile membership is deliberately *not* turned into facts (the
    sidebar, ``console_status`` and ``manage_hosts`` already show it, and it
    dominated the graph); ``hosts`` is accepted for compatibility and ignored."""
    del hosts
    facts: list[dict[str, Any]] = []
    catalog = catalog or {}

    def add(kind: str, about: list[str], text: str) -> None:
        try:
            facts.append(
                make_fact(
                    kind=kind,
                    about=about,
                    text=text,
                    status="observed",
                    source="config",
                )
            )
        except ValueError:
            pass

    for t in triggers:
        name = str(t.get("name") or "").strip()
        if not name:
            continue
        source = str(t.get("source") or "").strip() or "an event"
        event = str(t.get("event") or "").strip()
        mode = str(t.get("mode") or "agent").strip()
        about = [f"trigger:{name}"]
        runs: list[str] = []
        targets = [str(t.get("run") or "")] + [
            str(a.get("run") or "")
            for a in (t.get("actions") or [])
            if isinstance(a, dict)
        ]
        for run in targets:
            tgt, runnable = _split_run(run)
            if runnable:
                about += [*tgt, f"runnable:{runnable}"]
                where = f" on {entity_name(tgt[0])}" if tgt else ""
                runs.append(f"{runnable}{where}")
        for r in t.get("runnables") or []:  # an agent-mode trigger's allowlist
            if str(r).strip():
                about.append(f"runnable:{str(r).strip()}")
        what = (
            f"runs {_join(runs, 5)}"
            if runs
            else ("starts an agent turn" if mode == "agent" else "takes no action")
        )
        on = f"{source} {event}".strip()
        state = "" if t.get("enabled", True) else " It is disabled."
        add(
            "procedure",
            about[:MAX_ABOUT],
            f"Trigger {name} fires on {on} and {what} ({mode} mode).{state}",
        )

    for s in schedules:
        sid = str(s.get("id") or s.get("name") or "").strip()
        if not sid:
            continue
        when = s.get("when") or {}
        cadence = (
            f"cron {when.get('cron')}"
            if when.get("cron")
            else f"every {when.get('every')}"
            if when.get("every")
            else "on a schedule"
        )
        action = str(s.get("action") or "runnable")
        about = [f"schedule:{sid}"]
        if action == "runnable" and s.get("runnable"):
            about.append(f"runnable:{s['runnable']}")
            if s.get("group"):
                about.append(f"group:{s['group']}")
                where = f" on group {s['group']}"
            else:
                hs = (
                    [s["host"]]
                    if s.get("host")
                    else list(s.get("hosts") or s.get("selected_hosts") or [])
                )
                about += [f"host:{h}" for h in hs[:4]]
                where = f" on {_join([str(h) for h in hs], 4)}" if hs else ""
            what = f"runs {s['runnable']}{where}"
        elif action == "runbook" and (s.get("runbook") or s.get("skill")):
            rb_id = str(s.get("runbook") or s.get("skill"))
            about.append(f"runbook:{rb_id}")
            what = f"runs runbook {rb_id}"
        elif action == "prompt":
            what = "starts an agent turn on a fixed prompt"
        else:
            what = f"does a {action.replace('_', ' ')} action"
        state = "" if s.get("enabled", True) else " It is disabled."
        add(
            "procedure", about[:MAX_ABOUT], f"Schedule {sid} {what} ({cadence}).{state}"
        )

    for rb in runbooks:
        rid = str(rb.get("id") or "").strip()
        if not rid:
            continue
        title = " ".join(str(rb.get("title") or "").split())
        body = " ".join(
            str(st.get("text") or "")
            for st in (rb.get("steps") or [])
            if isinstance(st, dict)
        )
        about = link_about([f"runbook:{rid}"], f"{title} {body}", catalog)
        used = [entity_name(a) for a in about if entity_type(a) == "runnable"]
        what = f": {title}" if title else ""
        uses = f" It uses {_join(used, 6)}." if used else ""
        add("procedure", about, f"Runbook {rid}{what}.{uses}")

    for f in filters:
        name = str(f.get("name") or "").strip()
        pipeline = " ".join(str(f.get("pipeline") or "").split())
        if not name or not pipeline:
            continue
        desc = " ".join(str(f.get("description") or "").split())
        text = f"File filter {name} applies `{pipeline[:200]}` when relaying or fetching files."
        if desc:
            text += f" {desc}"
        add("procedure", [f"topic:file filter {name}"], text)

    seen: set[str] = set()
    out = []
    for f in facts:
        if f["id"] not in seen:
            seen.add(f["id"])
            out.append(f)
    return out


# ── AI distillation helpers (prompt + parse; the bridge makes the call) ─────


#: How much of each tool result the distill transcript carries — enough to see
#: what one call found and the next one used, not the whole output.
TOOL_OUTPUT_EXCERPT = 300


def redact_secrets(text: str) -> str:
    """``text`` with anything matching a secret pattern replaced by «redacted»."""
    for pat, _what in _SECRET_PATTERNS:
        text = pat.sub("«redacted»", text)
    return text


def render_turns(turns: list[dict[str, Any]]) -> str:
    """Chat turns as the plain transcript the distill prompt reads: the operator,
    each tool call (name + input) with the start of its result, and the agent's
    reply. Results are cut to :data:`TOOL_OUTPUT_EXCERPT` characters and
    secret-looking text is redacted — enough for the model to see that one
    tool's output fed the next call (``list_files`` found the log that
    ``relay_file`` then fetched)."""
    lines: list[str] = []
    for t in turns:
        user = str(t.get("user") or "").strip()
        if user:
            lines.append(f"OPERATOR: {user[:800]}")
        for tool in t.get("tools") or []:
            name = str(tool.get("name") or "")
            ti = tool.get("input")
            lines.append(f"TOOL {name}: {redact_secrets(str(ti)[:300])}")
            out = " ".join(str(tool.get("output") or "").split())
            if out:
                cut = "…" if len(out) > TOOL_OUTPUT_EXCERPT else ""
                lines.append(
                    f"RESULT: {redact_secrets(out[:TOOL_OUTPUT_EXCERPT])}{cut}"
                )
        reply = str(t.get("assistant") or "").strip()
        if reply:
            lines.append(f"AGENT: {reply[:800]}")
        lines.append("")
    return "\n".join(lines)


def chunk_transcripts(
    blocks: list[tuple[str, str]], max_chars: int = 24000
) -> list[tuple[str, list[str]]]:
    """Pack ``(key, text)`` blocks (one per conversation) into chunks of at most
    ``max_chars`` so a long history becomes several model calls instead of being
    cut off. Returns ``(chunk_text, keys_finished_in_chunk)``: a key is listed on
    the chunk holding its *last* piece, so a caller marks a conversation done only
    once all of it has been read. An oversized block is split on line breaks."""
    max_chars = max(1000, int(max_chars))
    pieces: list[tuple[str, str | None]] = []
    for key, text in blocks:
        text = text.strip()
        if not text:
            pieces.append(("", key))
            continue
        parts: list[str] = []
        cur = ""
        for line in text.split("\n"):
            line = line[:max_chars]
            if cur and len(cur) + len(line) + 1 > max_chars:
                parts.append(cur)
                cur = ""
            cur = f"{cur}\n{line}" if cur else line
        parts.append(cur)
        for i, part in enumerate(parts):
            pieces.append((part, key if i == len(parts) - 1 else None))
    chunks: list[tuple[str, list[str]]] = []
    text_acc = ""
    keys: list[str] = []
    for part, done_key in pieces:
        if text_acc and part and len(text_acc) + len(part) + 2 > max_chars:
            chunks.append((text_acc, keys))
            text_acc, keys = "", []
        if part:
            text_acc = f"{text_acc}\n\n{part}" if text_acc else part
        if done_key is not None:
            keys.append(done_key)
    if text_acc or keys:
        chunks.append((text_acc, keys))
    return chunks


def build_distill_prompt(
    turns: list[dict[str, Any]] | None = None,
    *,
    known: list[str],
    max_chars: int = 24000,
    transcript: str | None = None,
    entities: list[str] | None = None,
) -> str:
    """Prompt asking the model to extract durable team knowledge from chats.
    Pass a pre-chunked ``transcript`` (see :func:`chunk_transcripts`), or
    ``turns`` (rendered, keeping the last ``max_chars``). ``known`` are existing
    fact texts, so it doesn't re-propose them."""
    if transcript is None:
        transcript = render_turns(turns or [])[-max_chars:]
    known_block = "\n".join(f"- {k}" for k in known[:80]) or "(none yet)"
    entity_block = ", ".join((entities or [])[:300]) or "(none listed)"
    kinds = ", ".join(FACT_KINDS)
    types = ", ".join(ENTITY_TYPES)
    return (
        "You maintain a team knowledge wiki for an operations console. Read the "
        "recent conversations below and extract durable facts worth sharing with "
        "the rest of the team: where files and logs live on which hosts, what team "
        "jargon means, which tools go together, discovered facts about hosts / "
        "groups / profiles, knock-on effects of changes, how the output of one "
        "tool is used as the input of another (RESULT lines show the start of "
        "each tool's output), and how the team usually does things.\n\n"
        "Rules:\n"
        "- Only facts that will still be true next week. No one-off results, no "
        "opinions, no secrets, passwords, tokens or personal data.\n"
        "- Nothing that differs per person: no usernames, emails or accounts "
        "someone ran a tool as, and no 'X usually runs Y'. It must hold for "
        "everyone on the team.\n"
        "- No argument values a tool already uses by default — only values "
        "someone chose.\n"
        "- One or two sentences each, specific (name hosts, paths, runnables).\n"
        "- Skip anything already in the known list.\n"
        f"- kind is one of: {kinds}.\n"
        f"- about lists the entities as type:name, type one of: {types}.\n"
        "- When a fact is about one of the fleet's existing entities below, use "
        "that exact type:name (a host group is group:, not term:).\n"
        "- At most 12 facts. Fewer is fine; none is fine.\n\n"
        "Reply with ONLY a JSON array, e.g.\n"
        '[{"kind": "location", "about": ["host:web-01", "app:orders"], '
        '"text": "orders logs are in /var/log/orders/app.log on web-01"}]\n\n'
        f"Existing entities: {entity_block}\n\n"
        f"Known facts:\n{known_block}\n\nConversations:\n{transcript}"
    )


def parse_distill(text: str) -> list[dict[str, Any]]:
    """Pull the JSON array of candidate facts out of a model reply (tolerates
    surrounding prose / a fenced block). Invalid entries are dropped."""
    import json

    s = text or ""
    start, end = s.find("["), s.rfind("]")
    if start < 0 or end <= start:
        return []
    try:
        data = json.loads(s[start : end + 1])
    except ValueError:
        return []
    out = []
    for d in data if isinstance(data, list) else []:
        if not isinstance(d, dict):
            continue
        about = d.get("about")
        if isinstance(about, str):
            about = [about]
        if not isinstance(about, list) or not str(d.get("text") or "").strip():
            continue
        out.append(
            {
                "kind": str(d.get("kind") or "note"),
                "about": about,
                "text": str(d["text"]),
            }
        )
    return out[:20]
