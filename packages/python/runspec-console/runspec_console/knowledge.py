"""
knowledge.py — the team knowledge wiki's local store, index and mechanical capture.

Where ``memory.py`` holds a small machine-local list of facts the agent remembers,
this is the **structured, shareable** layer: facts *about* named entities (hosts,
groups, profiles, runnables, files, team jargon, …) that link together into a
graph and render as one wiki page per entity. Design note:
``docs/design/console-knowledge-wiki.md``.

Files are the source of truth (TOML ``[[fact]]`` collections, diffable and, later,
pushable by Memory Sync); a SQLite index under the same directory is a derived
cache rebuilt whenever a source file changes. Layout under ``knowledge_dir()``::

    facts.toml     approved facts authored on this console (this operator's lane)
    inbox.toml     proposed facts awaiting the operator's review (never shared)
    observed.toml  mechanical observations, regenerated by ``capture`` (usage
                   patterns mined from run history — no AI involved)
    team/*.toml    facts pulled from the team wiki (Memory Sync; read-only here)
    index.sqlite   derived search/graph cache — safe to delete

A fact::

    [[fact]]
    id = "k_3f9a1c0b2d"         # hash of kind + subjects + text, so the same fact
                                # proposed twice (or by two consoles) dedupes
    kind = "location"
    about = ["host:web-01", "runnable:tail-log"]
    text = "orders-svc logs live in /var/log/orders/app.log"
    status = "approved"         # approved | pending | observed | retired
    source = "agent"            # agent | mcp | operator | distill | capture | trigger:<name>
    author = "jason@desk-01"
    evidence = ["run:abc123"]    # ids only, never transcript text
    first_seen = "2026-10-04"
    last_confirmed = "2026-10-04"
    confirmations = 1

Everything here is stdlib (``sqlite3``; FTS5 when the build has it, a token-overlap
fallback otherwise) and pure apart from the file/index I/O, so it unit-tests on any
OS. The bridge (``bridge_knowledge.py``) owns when to read and write.
"""

from __future__ import annotations

import hashlib
import os
import re
import sqlite3
import sys
import threading
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable

import tomli_w

if sys.version_info >= (3, 11):
    import tomllib
else:
    import tomli as tomllib

_LOCK = threading.RLock()

FACTS_FILE = "facts.toml"
INBOX_FILE = "inbox.toml"
OBSERVED_FILE = "observed.toml"
TEAM_DIR = "team"
INDEX_FILE = "index.sqlite"
#: Machine-local bookkeeping (capture range, which chats were already distilled).
#: Never shared — it describes this console, not the team's knowledge.
STATE_FILE = "state.toml"

#: Entity types a fact can be about. Free-form ``type:name`` refs with another type
#: are kept (as ``topic``-like nodes); these are the ones the UI colours and the
#: tool schema advertises.
ENTITY_TYPES = (
    "host",
    "group",
    "profile",
    "runnable",
    "file",
    "term",
    "app",
    "service",
    "team",
    "trigger",
    "schedule",
    "runbook",
    "topic",
)

#: What a fact says. ``note`` is the catch-all.
FACT_KINDS = (
    "location",  # where something lives (a log, a config, a share)
    "glossary",  # what a team term / jargon means
    "pairing",  # tools that go together / run after one another
    "host",  # discovered info about a host, group or profile
    "effect",  # knock-on effects of changing something
    "arg-habit",  # the args a runnable is usually run with
    "procedure",  # how the team does something (lighter than a runbook)
    "note",
)

STATUSES = ("approved", "pending", "observed", "retired")

# Mechanical-capture thresholds: a pattern must repeat this often to be worth a fact.
MIN_RUNS = 3
HABIT_SHARE = (
    0.6  # an arg value must appear in at least this share of a runnable's runs
)
PAIR_WINDOW_S = 15 * 60  # "run after" = the same operator, within 15 minutes
MAX_VALUE_LEN = 160

_WORD = re.compile(r"[a-z0-9]+")


# ── small helpers ────────────────────────────────────────────────────────────


def _today() -> str:
    return datetime.now(timezone.utc).date().isoformat()


def _tokens(text: str) -> set[str]:
    return set(_WORD.findall(text.lower()))


def normalize_entity(ref: Any) -> str:
    """``"Host: web-01 "`` → ``"host:web-01"``. A bare name becomes ``topic:<name>``.
    The type is lower-cased; the name keeps its case (paths and host names are
    case-sensitive on some systems) but is whitespace-trimmed. ``""`` for blank."""
    s = str(ref or "").strip()
    if not s:
        return ""
    if ":" in s and not re.match(r"^[A-Za-z]:[\\/]", s):  # not a Windows drive path
        kind, _, name = s.partition(":")
        kind = kind.strip().lower()
        name = name.strip()
        if kind and name and re.fullmatch(r"[a-z][a-z0-9_-]{0,23}", kind):
            return f"{kind}:{name}"
    return f"topic:{s}"


def entity_type(ref: str) -> str:
    return ref.partition(":")[0] if ":" in ref else "topic"


def entity_name(ref: str) -> str:
    return ref.partition(":")[2] if ":" in ref else ref


def fact_id(kind: str, about: Iterable[str], text: str) -> str:
    """Deterministic id: the same fact proposed twice, or by two consoles, lands on
    the same id and merges (confirmations add up) instead of duplicating."""
    norm_text = " ".join(_WORD.findall(text.lower()))
    key = "|".join([kind, ",".join(sorted(about)), norm_text])
    return "k_" + hashlib.sha1(key.encode("utf-8")).hexdigest()[:10]


# Patterns that mean "this text carries a credential" — such a fact is refused
# rather than stored, since facts are meant to be shared across the team.
_SECRET_PATTERNS = (
    (re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"), "a private key"),
    (re.compile(r"\bAKIA[0-9A-Z]{16}\b"), "an AWS access key"),
    (
        re.compile(r"\b(gh[pousr]_[A-Za-z0-9]{20,}|glpat-[A-Za-z0-9_-]{16,})"),
        "a git token",
    ),
    (re.compile(r"\bxox[abpr]-[A-Za-z0-9-]{10,}"), "a Slack token"),
    (re.compile(r"\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\."), "a JWT"),
    (re.compile(r"(?i)\bbearer\s+[A-Za-z0-9._~+/-]{20,}"), "a bearer token"),
    (
        re.compile(
            r"(?i)\b(password|passwd|pwd|secret|api[_-]?key|token|pat)\s*[:=]\s*\S{4,}"
        ),
        "a password or key assignment",
    ),
)


def secret_reason(text: str) -> str:
    """Why ``text`` looks like it carries a secret, or ``""`` when it doesn't."""
    for pat, what in _SECRET_PATTERNS:
        if pat.search(text or ""):
            return what
    return ""


def make_fact(
    *,
    kind: str,
    about: Iterable[Any],
    text: str,
    status: str,
    source: str,
    author: str = "",
    evidence: Iterable[str] = (),
    confirmations: int = 1,
    first_seen: str = "",
    last_confirmed: str = "",
) -> dict[str, Any]:
    """Build a normalised fact dict (raises ``ValueError`` on bad input)."""
    text = " ".join(str(text or "").split())
    if not text:
        raise ValueError("a fact needs text")
    if len(text) > 1000:
        raise ValueError("a fact is one or two sentences (max 1000 characters)")
    why = secret_reason(text)
    if why:
        raise ValueError(
            f"the fact looks like it contains {why}; facts are shared, so leave secrets out"
        )
    kind = str(kind or "note").strip().lower()
    if kind not in FACT_KINDS:
        kind = "note"
    refs = sorted({r for r in (normalize_entity(a) for a in about) if r})
    if not refs:
        raise ValueError("a fact must be about at least one entity (e.g. host:web-01)")
    if status not in STATUSES:
        raise ValueError(f"unknown status {status!r}")
    today = _today()
    return {
        "id": fact_id(kind, refs, text),
        "kind": kind,
        "about": refs,
        "text": text,
        "status": status,
        "source": str(source or "agent"),
        "author": str(author or ""),
        "evidence": [str(e) for e in evidence if str(e).strip()][:10],
        "first_seen": first_seen or today,
        "last_confirmed": last_confirmed or today,
        "confirmations": max(1, int(confirmations or 1)),
    }


# ── file I/O ─────────────────────────────────────────────────────────────────


def _load(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    try:
        with open(path, "rb") as fh:
            data = tomllib.load(fh)
    except (OSError, tomllib.TOMLDecodeError):
        return []
    rows = data.get("fact")
    return (
        [dict(r) for r in rows if isinstance(r, dict)] if isinstance(rows, list) else []
    )


def _save(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    # Stable order (by id) so the file diffs cleanly when it is shared through git.
    rows = sorted(rows, key=lambda r: str(r.get("id", "")))
    text = tomli_w.dumps({"fact": rows}, multiline_strings=True)
    tmp = path.with_name(f"{path.name}.tmp.{os.getpid()}")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


class KnowledgeStore:
    """The knowledge directory: source files + the derived SQLite index."""

    def __init__(self, root: Path) -> None:
        self.root = Path(root)

    # -- source files ------------------------------------------------------

    def _path(self, name: str) -> Path:
        return self.root / name

    def own_facts(self) -> list[dict[str, Any]]:
        return _load(self._path(FACTS_FILE))

    def inbox(self) -> list[dict[str, Any]]:
        return _load(self._path(INBOX_FILE))

    def observed(self) -> list[dict[str, Any]]:
        return _load(self._path(OBSERVED_FILE))

    def team_facts(self) -> list[dict[str, Any]]:
        team = self.root / TEAM_DIR
        if not team.is_dir():
            return []
        out: list[dict[str, Any]] = []
        for p in sorted(team.glob("*.toml")):
            for r in _load(p):
                r.setdefault("status", "approved")
                out.append(r)
        return out

    def source_files(self) -> list[Path]:
        files = [self._path(n) for n in (FACTS_FILE, INBOX_FILE, OBSERVED_FILE)]
        team = self.root / TEAM_DIR
        if team.is_dir():
            files += sorted(team.glob("*.toml"))
        return files

    def all_facts(self) -> list[dict[str, Any]]:
        """Every fact the wiki shows, merged by id. Own approved facts win over a
        team copy of the same id (local edits take precedence); confirmations from
        the team copy are added in so the count reflects everyone. Inbox facts are
        included with ``status = "pending"``; retired ones are kept (the UI and
        search filter them)."""
        merged: dict[str, dict[str, Any]] = {}
        for r in self.team_facts():
            merged[str(r.get("id"))] = dict(r)
        for r in self.observed():
            merged.setdefault(str(r.get("id")), dict(r))
        for r in self.own_facts():
            rid = str(r.get("id"))
            team = merged.get(rid)
            row = dict(r)
            if team and team.get("status") != "observed":
                row["confirmations"] = int(row.get("confirmations", 1)) + int(
                    team.get("confirmations", 1)
                )
            merged[rid] = row
        for r in self.inbox():
            merged.setdefault(str(r.get("id")), dict(r, status="pending"))
        return list(merged.values())

    # -- mutations ---------------------------------------------------------

    def propose(self, fact: dict[str, Any]) -> tuple[str, str]:
        """Add a proposed fact to the inbox. Returns ``(id, outcome)`` where outcome
        is ``"proposed"``, ``"already-pending"``, or ``"confirmed"`` (the fact is
        already approved, so its confirmation count goes up instead)."""
        with _LOCK:
            own = self.own_facts()
            for r in own:
                if r.get("id") == fact["id"] and r.get("status") != "retired":
                    r["confirmations"] = int(r.get("confirmations", 1)) + 1
                    r["last_confirmed"] = _today()
                    _save(self._path(FACTS_FILE), own)
                    return fact["id"], "confirmed"
            inbox = self.inbox()
            for r in inbox:
                if r.get("id") == fact["id"]:
                    r["confirmations"] = int(r.get("confirmations", 1)) + 1
                    r["last_confirmed"] = _today()
                    _save(self._path(INBOX_FILE), inbox)
                    return fact["id"], "already-pending"
            inbox.append(dict(fact, status="pending"))
            _save(self._path(INBOX_FILE), inbox)
            return fact["id"], "proposed"

    def add_approved(self, fact: dict[str, Any]) -> str:
        """Write a fact straight into this console's approved facts (the operator
        authoring one in the Knowledge tab). Merges with an existing id."""
        with _LOCK:
            own = self.own_facts()
            for r in own:
                if r.get("id") == fact["id"]:
                    r.update(
                        status="approved",
                        last_confirmed=_today(),
                        confirmations=int(r.get("confirmations", 1)) + 1,
                    )
                    _save(self._path(FACTS_FILE), own)
                    return fact["id"]
            own.append(dict(fact, status="approved"))
            _save(self._path(FACTS_FILE), own)
            return fact["id"]

    def review(
        self, fid: str, approve: bool, edits: dict[str, Any] | None = None
    ) -> dict[str, Any] | None:
        """Approve (optionally edited) or reject a pending fact. Returns the approved
        fact, ``{}`` for a rejection, or ``None`` when ``fid`` isn't in the inbox."""
        with _LOCK:
            inbox = self.inbox()
            hit = next((r for r in inbox if r.get("id") == fid), None)
            if hit is None:
                return None
            rest = [r for r in inbox if r.get("id") != fid]
            if not approve:
                _save(self._path(INBOX_FILE), rest)
                return {}
            fact = dict(hit)
            if edits:
                fact = make_fact(
                    kind=edits.get("kind", hit.get("kind")),
                    about=edits.get("about", hit.get("about", [])),
                    text=edits.get("text", hit.get("text", "")),
                    status="approved",
                    source=str(hit.get("source", "")),
                    author=str(hit.get("author", "")),
                    evidence=hit.get("evidence", []),
                    confirmations=int(hit.get("confirmations", 1)),
                    first_seen=str(hit.get("first_seen", "")),
                )
            self.add_approved(dict(fact, status="approved"))
            _save(self._path(INBOX_FILE), rest)
            return dict(fact, status="approved")

    def edit(self, fid: str, edits: dict[str, Any]) -> dict[str, Any] | None:
        """Edit an approved fact this console owns (or adopt a team/observed fact
        into the local lane with the edit applied). The edited fact gets a new id
        when its text/subjects change; the old one is retired so a team copy
        doesn't resurface. ``None`` when ``fid`` is unknown."""
        with _LOCK:
            current = next((r for r in self.all_facts() if r.get("id") == fid), None)
            if current is None or current.get("status") == "pending":
                return None
            fact = make_fact(
                kind=edits.get("kind", current.get("kind")),
                about=edits.get("about", current.get("about", [])),
                text=edits.get("text", current.get("text", "")),
                status="approved",
                source="operator",
                author=str(edits.get("author") or current.get("author", "")),
                evidence=current.get("evidence", []),
                confirmations=int(current.get("confirmations", 1)),
                first_seen=str(current.get("first_seen", "")),
            )
            own = [r for r in self.own_facts() if r.get("id") not in (fid, fact["id"])]
            if fact["id"] != fid:
                own.append(dict(current, status="retired", last_confirmed=_today()))
            own.append(fact)
            _save(self._path(FACTS_FILE), own)
            return fact

    def retire(self, fid: str) -> bool:
        """Mark a fact retired (kept, so a shared copy can be retired everywhere
        once Memory Sync carries it). Pending facts are simply dropped."""
        with _LOCK:
            inbox = self.inbox()
            if any(r.get("id") == fid for r in inbox):
                _save(self._path(INBOX_FILE), [r for r in inbox if r.get("id") != fid])
                return True
            current = next((r for r in self.all_facts() if r.get("id") == fid), None)
            if current is None:
                return False
            own = [r for r in self.own_facts() if r.get("id") != fid]
            own.append(dict(current, status="retired", last_confirmed=_today()))
            _save(self._path(FACTS_FILE), own)
            return True

    def relink(self, fn: Any) -> int:
        """Rewrite the ``about`` of inbox and own (non-retired) facts through
        ``fn(about, text) -> about`` — e.g. :func:`link_about` after the fleet
        gained a group. A fact whose subjects change gets its new content id;
        everything else (status, source, author, confirmations) is kept. Returns
        how many facts changed."""
        changed = 0
        with _LOCK:
            for name in (INBOX_FILE, FACTS_FILE):
                rows = _load(self._path(name))
                out: list[dict[str, Any]] = []
                dirty = False
                for row in rows:
                    if row.get("status") == "retired":
                        out.append(row)
                        continue
                    about = list(row.get("about") or [])
                    new = sorted(set(fn(about, str(row.get("text") or ""))))
                    if new and new != sorted(about):
                        row = dict(row, about=new)
                        row["id"] = fact_id(
                            str(row.get("kind")), new, str(row.get("text"))
                        )
                        dirty = True
                        changed += 1
                    out.append(row)
                if dirty:
                    seen: dict[str, dict[str, Any]] = {}
                    for row in out:  # two facts can converge on one id — keep one
                        seen.setdefault(str(row.get("id")), row)
                    _save(self._path(name), list(seen.values()))
        return changed

    def write_observed(self, facts: list[dict[str, Any]]) -> None:
        with _LOCK:
            _save(self._path(OBSERVED_FILE), facts)

    # -- machine-local state ------------------------------------------------

    def state(self) -> dict[str, Any]:
        path = self._path(STATE_FILE)
        if not path.exists():
            return {}
        try:
            with open(path, "rb") as fh:
                data = tomllib.load(fh)
        except (OSError, tomllib.TOMLDecodeError):
            return {}
        return dict(data)

    def update_state(self, **changes: Any) -> dict[str, Any]:
        """Merge ``changes`` into the state file (a ``distilled`` dict is merged
        key by key, everything else replaced)."""
        with _LOCK:
            state = self.state()
            for key, value in changes.items():
                if key == "distilled" and isinstance(value, dict):
                    merged = dict(state.get("distilled") or {})
                    merged.update(value)
                    state["distilled"] = merged
                else:
                    state[key] = value
            path = self._path(STATE_FILE)
            path.parent.mkdir(parents=True, exist_ok=True)
            tmp = path.with_name(f"{path.name}.tmp.{os.getpid()}")
            tmp.write_text(tomli_w.dumps(state), encoding="utf-8")
            os.replace(tmp, path)
            return state

    # -- derived index -----------------------------------------------------

    def _signature(self) -> str:
        parts = []
        for p in self.source_files():
            try:
                st = p.stat()
                parts.append(f"{p.name}:{st.st_mtime_ns}:{st.st_size}")
            except OSError:
                parts.append(f"{p.name}:-")
        return "|".join(parts)

    def index(self) -> "KnowledgeIndex":
        """The SQLite index, rebuilt first if any source file changed."""
        with _LOCK:
            return KnowledgeIndex.open(
                self.root / INDEX_FILE, self._signature(), self.all_facts
            )


class KnowledgeIndex:
    """Derived SQLite cache over all facts: ranked search (FTS5 BM25 when the
    sqlite build has it) and the entity graph. Never synced; rebuilt from files."""

    def __init__(self, conn: sqlite3.Connection, fts: bool) -> None:
        self.conn = conn
        self.fts = fts

    @classmethod
    def open(cls, path: Path, signature: str, facts_fn: Any) -> "KnowledgeIndex":
        path.parent.mkdir(parents=True, exist_ok=True)
        conn = sqlite3.connect(str(path), check_same_thread=False)
        conn.row_factory = sqlite3.Row
        conn.execute("CREATE TABLE IF NOT EXISTS meta (k TEXT PRIMARY KEY, v TEXT)")
        row = conn.execute("SELECT v FROM meta WHERE k='signature'").fetchone()
        fts_row = conn.execute("SELECT v FROM meta WHERE k='fts'").fetchone()
        if row is None or row["v"] != signature:
            fts = cls._rebuild(conn, facts_fn())
            conn.execute(
                "INSERT OR REPLACE INTO meta VALUES ('signature', ?), ('fts', ?)",
                (signature, "1" if fts else "0"),
            )
            conn.commit()
        else:
            fts = bool(fts_row and fts_row["v"] == "1")
        return cls(conn, fts)

    @staticmethod
    def _rebuild(conn: sqlite3.Connection, facts: list[dict[str, Any]]) -> bool:
        conn.executescript(
            """
            DROP TABLE IF EXISTS facts;
            DROP TABLE IF EXISTS about;
            DROP TABLE IF EXISTS facts_fts;
            CREATE TABLE facts (
                id TEXT PRIMARY KEY, kind TEXT, text TEXT, status TEXT, source TEXT,
                author TEXT, first_seen TEXT, last_confirmed TEXT,
                confirmations INTEGER, evidence TEXT
            );
            CREATE TABLE about (fact_id TEXT, entity TEXT, etype TEXT);
            CREATE INDEX about_entity ON about(entity);
            CREATE INDEX about_fact ON about(fact_id);
            """
        )
        fts = True
        try:
            conn.execute(
                "CREATE VIRTUAL TABLE facts_fts USING fts5(id UNINDEXED, body)"
            )
        except sqlite3.OperationalError:
            fts = False
        for f in facts:
            fid = str(f.get("id") or "")
            if not fid:
                continue
            about = [str(a) for a in f.get("about", []) or []]
            conn.execute(
                "INSERT OR REPLACE INTO facts VALUES (?,?,?,?,?,?,?,?,?,?)",
                (
                    fid,
                    str(f.get("kind", "note")),
                    str(f.get("text", "")),
                    str(f.get("status", "approved")),
                    str(f.get("source", "")),
                    str(f.get("author", "")),
                    str(f.get("first_seen", "")),
                    str(f.get("last_confirmed", "")),
                    int(f.get("confirmations", 1) or 1),
                    "\n".join(str(e) for e in f.get("evidence", []) or []),
                ),
            )
            for a in about:
                conn.execute(
                    "INSERT INTO about VALUES (?,?,?)", (fid, a, entity_type(a))
                )
            if fts:
                body = " ".join(
                    [str(f.get("text", "")), str(f.get("kind", ""))]
                    + [entity_name(a) for a in about]
                )
                conn.execute("INSERT INTO facts_fts VALUES (?, ?)", (fid, body))
        return fts

    # -- queries -----------------------------------------------------------

    def _abouts(self, ids: list[str]) -> dict[str, list[str]]:
        out: dict[str, list[str]] = defaultdict(list)
        if not ids:
            return out
        marks = ",".join("?" * len(ids))
        for r in self.conn.execute(
            f"SELECT fact_id, entity FROM about WHERE fact_id IN ({marks}) ORDER BY entity",
            ids,
        ):
            out[r["fact_id"]].append(r["entity"])
        return out

    def _rows(self, rows: list[sqlite3.Row]) -> list[dict[str, Any]]:
        ids = [r["id"] for r in rows]
        abouts = self._abouts(ids)
        return [
            {
                "id": r["id"],
                "kind": r["kind"],
                "text": r["text"],
                "about": abouts.get(r["id"], []),
                "status": r["status"],
                "source": r["source"],
                "author": r["author"],
                "first_seen": r["first_seen"],
                "last_confirmed": r["last_confirmed"],
                "confirmations": r["confirmations"],
                "evidence": [e for e in (r["evidence"] or "").split("\n") if e],
            }
            for r in rows
        ]

    def search(
        self,
        query: str,
        *,
        kind: str = "",
        entity: str = "",
        include_pending: bool = False,
        limit: int = 10,
    ) -> list[dict[str, Any]]:
        """Facts ranked for ``query`` (BM25 + confirmations), excluding retired (and,
        by default, pending) facts. An empty query lists the most-confirmed."""
        statuses = ["approved", "observed"] + (["pending"] if include_pending else [])
        where = [f"f.status IN ({','.join('?' * len(statuses))})"]
        params: list[Any] = list(statuses)
        if kind:
            where.append("f.kind = ?")
            params.append(kind)
        if entity:
            where.append("f.id IN (SELECT fact_id FROM about WHERE entity = ?)")
            params.append(normalize_entity(entity))
        limit = max(1, min(int(limit or 10), 100))
        q_tokens = sorted(_tokens(query or ""))
        if q_tokens and self.fts:
            match = " OR ".join(f'"{t}"' for t in q_tokens)
            sql = (
                "SELECT f.*, bm25(facts_fts) AS rank FROM facts_fts "
                "JOIN facts f ON f.id = facts_fts.id "
                f"WHERE facts_fts MATCH ? AND {' AND '.join(where)} "
                "ORDER BY rank - (f.confirmations * 0.05) LIMIT ?"
            )
            rows = list(self.conn.execute(sql, [match, *params, limit]))
            return self._rows(rows)
        sql = f"SELECT f.* FROM facts f WHERE {' AND '.join(where)}"
        rows = list(self.conn.execute(sql, params))
        if q_tokens:
            q = set(q_tokens)
            abouts = self._abouts([r["id"] for r in rows])
            scored = []
            for r in rows:
                hay = _tokens(
                    r["text"]
                    + " "
                    + " ".join(entity_name(a) for a in abouts.get(r["id"], []))
                )
                s = len(q & hay)
                if s:
                    scored.append((s, r["confirmations"], r))
            scored.sort(key=lambda t: (t[0], t[1]), reverse=True)
            rows = [r for _s, _c, r in scored]
        else:
            rows.sort(
                key=lambda r: (r["confirmations"], r["last_confirmed"]), reverse=True
            )
        return self._rows(rows[:limit])

    def page(self, entity: str, *, include_pending: bool = True) -> dict[str, Any]:
        """One entity's wiki page: its facts (grouped by kind in the UI), linked
        entities with weights, and freshness/contributor summaries."""
        ref = normalize_entity(entity)
        statuses = ["approved", "observed"] + (["pending"] if include_pending else [])
        rows = list(
            self.conn.execute(
                f"SELECT f.* FROM facts f JOIN about a ON a.fact_id = f.id "
                f"WHERE a.entity = ? AND f.status IN ({','.join('?' * len(statuses))}) "
                "ORDER BY f.kind, f.confirmations DESC, f.last_confirmed DESC",
                [ref, *statuses],
            )
        )
        facts = self._rows(rows)
        linked: Counter[str] = Counter()
        for f in facts:
            for a in f["about"]:
                if a != ref:
                    linked[a] += int(f["confirmations"] or 1)
        return {
            "entity": ref,
            "type": entity_type(ref),
            "name": entity_name(ref),
            "facts": facts,
            "links": [{"entity": e, "weight": w} for e, w in linked.most_common(40)],
            "authors": sorted({f["author"] for f in facts if f["author"]}),
            "last_confirmed": max((f["last_confirmed"] for f in facts), default=""),
        }

    def graph(
        self, *, entity: str = "", depth: int = 1, max_nodes: int = 300
    ) -> dict[str, Any]:
        """Nodes (entities, weighted by the confirmations of facts about them) and
        edges (entities sharing a fact, weighted the same way). With ``entity``,
        just its neighbourhood out to ``depth`` hops."""
        live = "('approved','observed','pending')"
        pairs = list(
            self.conn.execute(
                "SELECT a1.entity AS s, a2.entity AS t, f.confirmations AS w, f.status AS st "
                "FROM about a1 JOIN about a2 ON a1.fact_id = a2.fact_id AND a1.entity < a2.entity "
                f"JOIN facts f ON f.id = a1.fact_id WHERE f.status IN {live}"
            )
        )
        weights: Counter[str] = Counter()
        counts: Counter[str] = Counter()
        pending_only: dict[str, bool] = {}
        last: dict[str, str] = {}
        for r in self.conn.execute(
            "SELECT a.entity AS e, f.confirmations AS w, f.status AS st, f.last_confirmed AS lc "
            f"FROM about a JOIN facts f ON f.id = a.fact_id WHERE f.status IN {live}"
        ):
            e = r["e"]
            weights[e] += int(r["w"] or 1)
            counts[e] += 1
            pending_only[e] = pending_only.get(e, True) and r["st"] == "pending"
            last[e] = max(last.get(e, ""), r["lc"] or "")
        edges: Counter[tuple[str, str]] = Counter()
        for r in pairs:
            edges[(r["s"], r["t"])] += int(r["w"] or 1)
        keep: set[str]
        if entity:
            ref = normalize_entity(entity)
            keep = {ref}
            frontier = {ref}
            for _ in range(max(1, min(int(depth or 1), 3))):
                nxt = set()
                for s, t in edges:
                    if s in frontier and t not in keep:
                        nxt.add(t)
                    elif t in frontier and s not in keep:
                        nxt.add(s)
                keep |= nxt
                frontier = nxt
        else:
            keep = set(weights)
        if len(keep) > max_nodes:
            keep = set(sorted(keep, key=lambda e: weights[e], reverse=True)[:max_nodes])
        nodes = [
            {
                "id": e,
                "type": entity_type(e),
                "name": entity_name(e),
                "weight": weights[e],
                "facts": counts[e],
                "pending": pending_only.get(e, False),
                "last_confirmed": last.get(e, ""),
            }
            for e in sorted(keep)
        ]
        links = [
            {"source": s, "target": t, "weight": w}
            for (s, t), w in sorted(edges.items())
            if s in keep and t in keep
        ]
        return {"nodes": nodes, "edges": links}

    def stats(self) -> dict[str, Any]:
        by_status = {
            r["status"]: r["n"]
            for r in self.conn.execute(
                "SELECT status, COUNT(*) AS n FROM facts GROUP BY status"
            )
        }
        entities = self.conn.execute(
            "SELECT COUNT(DISTINCT a.entity) AS n FROM about a JOIN facts f "
            "ON f.id = a.fact_id WHERE f.status != 'retired'"
        ).fetchone()["n"]
        return {
            "approved": by_status.get("approved", 0),
            "observed": by_status.get("observed", 0),
            "pending": by_status.get("pending", 0),
            "retired": by_status.get("retired", 0),
            "entities": entities,
            "fts": self.fts,
        }

    def close(self) -> None:
        try:
            self.conn.close()
        except Exception:  # noqa: BLE001
            pass


# ── mechanical capture (no AI) ───────────────────────────────────────────────


def _parse_ts(ts: Any) -> datetime | None:
    s = str(ts or "").strip()
    if not s:
        return None
    try:
        dt = datetime.fromisoformat(s.replace("Z", "+00:00"))
    except ValueError:
        return None
    return dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)


def _looks_like_path(v: str) -> bool:
    return (
        bool(re.match(r"^(/[^\s]+|[A-Za-z]:[\\/][^\n]*|~/[^\s]+)$", v)) and len(v) > 2
    )


def _runnable_label(row: dict[str, Any]) -> str:
    name = str(row.get("runnable") or "").strip()
    path = [str(p) for p in (row.get("commandPath") or []) if str(p).strip()]
    return " ".join([name, *path]) if path else name


def observe(
    history: list[dict[str, Any]],
    *,
    min_runs: int = MIN_RUNS,
    habit_share: float = HABIT_SHARE,
    pair_window_s: int = PAIR_WINDOW_S,
) -> list[dict[str, Any]]:
    """Mine run-history rows (``get_history_all`` shape) into ``observed`` facts:

    * **arg habits** — a runnable is usually run with ``arg=value`` (a value seen
      in ≥ ``habit_share`` of its runs, at least ``min_runs`` times); path values
      also link a ``file:`` entity,
    * **host usage** — a runnable is used on a host (≥ ``min_runs`` runs),
    * **pairings** — runnable B is often run after A by the same operator within
      ``pair_window_s`` (≥ ``min_runs`` times).

    Deterministic: same history → same facts (ids are content hashes)."""
    rows = [
        r
        for r in history
        if str(r.get("runnable") or "").strip()
        and r.get("kind") in (None, "", "runnable")
        and str(r.get("runnable")) != "chat"
    ]
    facts: list[dict[str, Any]] = []

    def add(
        kind: str, about: list[str], text: str, n: int, runs: list[dict[str, Any]]
    ) -> None:
        stamps = sorted(str(r.get("ts") or "")[:10] for r in runs if r.get("ts"))
        evidence = [
            f"run:{r.get('runId') or r.get('id')}"
            for r in runs[-5:]
            if r.get("runId") or r.get("id")
        ]
        try:
            facts.append(
                make_fact(
                    kind=kind,
                    about=about,
                    text=text,
                    status="observed",
                    source="capture",
                    author="",
                    evidence=evidence,
                    confirmations=n,
                    first_seen=stamps[0] if stamps else "",
                    last_confirmed=stamps[-1] if stamps else "",
                )
            )
        except ValueError:
            pass  # e.g. a value that looks like a secret — never stored

    by_runnable: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for r in rows:
        by_runnable[_runnable_label(r)].append(r)

    for label, runs in sorted(by_runnable.items()):
        base = str(runs[0].get("runnable"))
        n = len(runs)
        # host usage
        by_host: dict[str, list[dict[str, Any]]] = defaultdict(list)
        for r in runs:
            h = str(r.get("host") or "").strip()
            if h:
                by_host[h].append(r)
        for host, hruns in sorted(by_host.items()):
            if len(hruns) >= min_runs:
                add(
                    "host",
                    [f"runnable:{base}", f"host:{host}"],
                    f"{label} is used on {host} ({len(hruns)} runs).",
                    len(hruns),
                    hruns,
                )
        # arg habits
        if n >= min_runs:
            values: dict[tuple[str, str], list[dict[str, Any]]] = defaultdict(list)
            for r in runs:
                args = r.get("args") or {}
                if not isinstance(args, dict):
                    continue
                for k, v in args.items():
                    if v is None or v is False or v == "" or v == []:
                        continue
                    sv = ", ".join(map(str, v)) if isinstance(v, list) else str(v)
                    if len(sv) > MAX_VALUE_LEN:
                        continue
                    values[(str(k), sv)].append(r)
            for (k, sv), vruns in sorted(values.items()):
                c = len(vruns)
                if c >= min_runs and c / n >= habit_share:
                    about = [f"runnable:{base}"]
                    if _looks_like_path(sv):
                        about.append(f"file:{sv}")
                    shown = "on" if sv == "True" else repr(sv)
                    add(
                        "arg-habit",
                        about,
                        f"{label} is usually run with {k} = {shown} ({c} of {n} runs).",
                        c,
                        vruns,
                    )

    # pairings: consecutive runs by the same operator inside the window
    seq = sorted(
        ((t, r) for r in rows if (t := _parse_ts(r.get("ts"))) is not None),
        key=lambda p: p[0],
    )
    last_by_op: dict[str, tuple[datetime, dict[str, Any]]] = {}
    pairs: dict[tuple[str, str], list[dict[str, Any]]] = defaultdict(list)
    for t, r in seq:
        op = str(r.get("operator") or "").strip()
        prev = last_by_op.get(op)
        if prev is not None:
            pt, pr = prev
            a, b = str(pr.get("runnable")), str(r.get("runnable"))
            if a != b and (t - pt).total_seconds() <= pair_window_s:
                pairs[(a, b)].append(r)
        last_by_op[op] = (t, r)
    for (a, b), pruns in sorted(pairs.items()):
        if len(pruns) >= min_runs:
            add(
                "pairing",
                [f"runnable:{a}", f"runnable:{b}"],
                f"{b} is often run after {a} ({len(pruns)} times).",
                len(pruns),
                pruns,
            )
    # A content-hash id can repeat (same text) — keep the first.
    seen: set[str] = set()
    out = []
    for f in facts:
        if f["id"] not in seen:
            seen.add(f["id"])
            out.append(f)
    return out


# ── linking facts to the fleet's real entities ──────────────────────────────

#: Entity types whose names are matched against a fact's text and against the
#: model's guesses, so a fact joins the existing node instead of floating alone.
LINKABLE_TYPES = (
    "host",
    "group",
    "profile",
    "runnable",
    "trigger",
    "schedule",
    "runbook",
)
#: Names too common to treat a bare mention in prose as a reference (they are
#: still linked when the fact names them as a subject).
_COMMON_NAMES = frozenset(
    {"local", "default", "all", "test", "main", "prod", "dev", "uat", "staging", "data"}
)
MAX_ABOUT = 8


def _name_key(name: str) -> str:
    """Spelling-insensitive key: ``"Linux Servers"`` == ``linux-servers``."""
    return "".join(_WORD.findall(str(name).lower()))


def entity_catalog(entities: Iterable[str]) -> dict[str, list[str]]:
    """``name key -> [refs]`` for the known entities (``type:name``), so a guess
    like ``term:Linux Servers`` resolves to ``group:Linux Servers``."""
    cat: dict[str, list[str]] = defaultdict(list)
    for ref in entities:
        ref = normalize_entity(ref)
        if not ref or entity_type(ref) not in LINKABLE_TYPES:
            continue
        key = _name_key(entity_name(ref))
        if key and ref not in cat[key]:
            cat[key].append(ref)
    return dict(cat)


def _resolve(ref: str, catalog: dict[str, list[str]]) -> str:
    kind = entity_type(ref)
    if kind == "file":
        return ref
    hits = catalog.get(_name_key(entity_name(ref)), [])
    if not hits:
        return ref
    same = [h for h in hits if entity_type(h) == kind]
    if same:
        return same[0]  # same type, canonical spelling
    return hits[0] if len(hits) == 1 else ref  # ambiguous across types: keep


def link_about(
    about: Iterable[str], text: str, catalog: dict[str, list[str]]
) -> list[str]:
    """A fact's subjects joined up with the fleet: each guessed ref resolved to
    the known entity of that name (any type, canonical spelling), plus every
    known host / group / profile / runnable / trigger / schedule / runbook the
    text names. Capped at :data:`MAX_ABOUT` subjects (named ones first)."""
    refs = [_resolve(r, catalog) for r in (normalize_entity(a) for a in about) if r]
    seen = set(refs)
    if catalog and text:
        low = f" {' '.join(_WORD.findall(text.lower()))} "
        names: list[tuple[str, str]] = []
        for hits in catalog.values():
            for h in hits:
                names.append((entity_name(h), h))
        # Longest names first, so "web-01-backup" wins over "web-01".
        for name, ref in sorted(names, key=lambda p: -len(p[0])):
            if ref in seen or len(refs) >= MAX_ABOUT:
                continue
            words = " ".join(_WORD.findall(name.lower()))
            if len(words) < 3 or words in _COMMON_NAMES:
                continue
            if f" {words} " in low:
                refs.append(ref)
                seen.add(ref)
                # Consume the match so "web-01" doesn't also hit inside
                # "web-01-backup".
                low = low.replace(f" {words} ", "  ")
    out: list[str] = []
    for r in refs:
        if r not in out:
            out.append(r)
    return out[:MAX_ABOUT]


# ── facts read from the console's own config (no AI) ────────────────────────


def _split_run(run: str) -> tuple[list[str], str]:
    """A trigger ``run`` target → (target refs, runnable). ``group:G__r`` → a
    group, ``host__r`` → a host, a bare ``r`` → no target."""
    run = str(run or "").strip()
    if "__" not in run:
        return [], run
    target, _, runnable = run.rpartition("__")
    if target.startswith("group:"):
        return [f"group:{target[6:]}"], runnable
    return [f"host:{target}"], runnable


def _join(names: list[str], limit: int = 12) -> str:
    shown = names[:limit]
    more = len(names) - len(shown)
    return ", ".join(shown) + (f" and {more} more" if more > 0 else "")


def observe_config(
    *,
    hosts: Iterable[dict[str, Any]] = (),
    triggers: Iterable[dict[str, Any]] = (),
    schedules: Iterable[dict[str, Any]] = (),
    runbooks: Iterable[dict[str, Any]] = (),
    filters: Iterable[dict[str, Any]] = (),
    catalog: dict[str, list[str]] | None = None,
) -> list[dict[str, Any]]:
    """Facts read straight from the console's config (``status = observed``,
    ``source = config``) so the wiki — and the graph — know how the fleet is
    set up: which hosts are in each group and profile, what each trigger and
    schedule runs where, what each runbook is for and which runnables it uses,
    and the saved file-relay filters. Rebuilt on every capture, so it never
    goes stale; the *why* behind the setup is what operators and chats add."""
    facts: list[dict[str, Any]] = []
    catalog = catalog or {}

    def add(kind: str, about: list[str], text: str) -> None:
        try:
            facts.append(
                make_fact(
                    kind=kind,
                    about=about,
                    text=text,
                    status="observed",
                    source="config",
                )
            )
        except ValueError:
            pass

    groups: dict[str, list[str]] = defaultdict(list)
    profiles: dict[str, list[str]] = defaultdict(list)
    for h in hosts:
        name = str(h.get("name") or "").strip()
        if not name:
            continue
        g = str(h.get("group") or "").strip()
        if g:
            groups[g].append(name)
        for p in h.get("profiles") or []:
            if str(p).strip():
                profiles[str(p).strip()].append(name)
    for g, members in sorted(groups.items()):
        members = sorted(set(members))
        add(
            "host",
            [f"group:{g}", *[f"host:{m}" for m in members[: MAX_ABOUT - 1]]],
            f"Group {g} contains {len(members)} host(s): {_join(members)}.",
        )
    for p, members in sorted(profiles.items()):
        members = sorted(set(members))
        add(
            "host",
            [f"profile:{p}", *[f"host:{m}" for m in members[: MAX_ABOUT - 1]]],
            f"Profile {p} loads {len(members)} host(s): {_join(members)}.",
        )

    for t in triggers:
        name = str(t.get("name") or "").strip()
        if not name:
            continue
        source = str(t.get("source") or "").strip() or "an event"
        event = str(t.get("event") or "").strip()
        mode = str(t.get("mode") or "agent").strip()
        about = [f"trigger:{name}"]
        runs: list[str] = []
        targets = [str(t.get("run") or "")] + [
            str(a.get("run") or "")
            for a in (t.get("actions") or [])
            if isinstance(a, dict)
        ]
        for run in targets:
            tgt, runnable = _split_run(run)
            if runnable:
                about += [*tgt, f"runnable:{runnable}"]
                where = f" on {entity_name(tgt[0])}" if tgt else ""
                runs.append(f"{runnable}{where}")
        for r in t.get("runnables") or []:  # an agent-mode trigger's allowlist
            if str(r).strip():
                about.append(f"runnable:{str(r).strip()}")
        what = (
            f"runs {_join(runs, 5)}"
            if runs
            else ("starts an agent turn" if mode == "agent" else "takes no action")
        )
        on = f"{source} {event}".strip()
        state = "" if t.get("enabled", True) else " It is disabled."
        add(
            "procedure",
            about[:MAX_ABOUT],
            f"Trigger {name} fires on {on} and {what} ({mode} mode).{state}",
        )

    for s in schedules:
        sid = str(s.get("id") or s.get("name") or "").strip()
        if not sid:
            continue
        when = s.get("when") or {}
        cadence = (
            f"cron {when.get('cron')}"
            if when.get("cron")
            else f"every {when.get('every')}"
            if when.get("every")
            else "on a schedule"
        )
        action = str(s.get("action") or "runnable")
        about = [f"schedule:{sid}"]
        if action == "runnable" and s.get("runnable"):
            about.append(f"runnable:{s['runnable']}")
            if s.get("group"):
                about.append(f"group:{s['group']}")
                where = f" on group {s['group']}"
            else:
                hs = (
                    [s["host"]]
                    if s.get("host")
                    else list(s.get("hosts") or s.get("selected_hosts") or [])
                )
                about += [f"host:{h}" for h in hs[:4]]
                where = f" on {_join([str(h) for h in hs], 4)}" if hs else ""
            what = f"runs {s['runnable']}{where}"
        elif action == "runbook" and (s.get("runbook") or s.get("skill")):
            rb_id = str(s.get("runbook") or s.get("skill"))
            about.append(f"runbook:{rb_id}")
            what = f"runs runbook {rb_id}"
        elif action == "prompt":
            what = "starts an agent turn on a fixed prompt"
        else:
            what = f"does a {action.replace('_', ' ')} action"
        state = "" if s.get("enabled", True) else " It is disabled."
        add(
            "procedure", about[:MAX_ABOUT], f"Schedule {sid} {what} ({cadence}).{state}"
        )

    for rb in runbooks:
        rid = str(rb.get("id") or "").strip()
        if not rid:
            continue
        title = " ".join(str(rb.get("title") or "").split())
        body = " ".join(
            str(st.get("text") or "")
            for st in (rb.get("steps") or [])
            if isinstance(st, dict)
        )
        about = link_about([f"runbook:{rid}"], f"{title} {body}", catalog)
        used = [entity_name(a) for a in about if entity_type(a) == "runnable"]
        what = f": {title}" if title else ""
        uses = f" It uses {_join(used, 6)}." if used else ""
        add("procedure", about, f"Runbook {rid}{what}.{uses}")

    for f in filters:
        name = str(f.get("name") or "").strip()
        pipeline = " ".join(str(f.get("pipeline") or "").split())
        if not name or not pipeline:
            continue
        desc = " ".join(str(f.get("description") or "").split())
        text = f"File filter {name} applies `{pipeline[:200]}` when relaying or fetching files."
        if desc:
            text += f" {desc}"
        add("procedure", [f"topic:file filter {name}"], text)

    seen: set[str] = set()
    out = []
    for f in facts:
        if f["id"] not in seen:
            seen.add(f["id"])
            out.append(f)
    return out


# ── AI distillation helpers (prompt + parse; the bridge makes the call) ─────


def render_turns(turns: list[dict[str, Any]]) -> str:
    """Chat turns as the plain transcript the distill prompt reads. Tool *outputs*
    are left out (size, and they can carry sensitive data); tool names + inputs
    are kept."""
    lines: list[str] = []
    for t in turns:
        user = str(t.get("user") or "").strip()
        if user:
            lines.append(f"OPERATOR: {user[:800]}")
        for tool in t.get("tools") or []:
            name = str(tool.get("name") or "")
            ti = tool.get("input")
            lines.append(f"TOOL {name}: {str(ti)[:300]}")
        reply = str(t.get("assistant") or "").strip()
        if reply:
            lines.append(f"AGENT: {reply[:800]}")
        lines.append("")
    return "\n".join(lines)


def chunk_transcripts(
    blocks: list[tuple[str, str]], max_chars: int = 24000
) -> list[tuple[str, list[str]]]:
    """Pack ``(key, text)`` blocks (one per conversation) into chunks of at most
    ``max_chars`` so a long history becomes several model calls instead of being
    cut off. Returns ``(chunk_text, keys_finished_in_chunk)``: a key is listed on
    the chunk holding its *last* piece, so a caller marks a conversation done only
    once all of it has been read. An oversized block is split on line breaks."""
    max_chars = max(1000, int(max_chars))
    pieces: list[tuple[str, str | None]] = []
    for key, text in blocks:
        text = text.strip()
        if not text:
            pieces.append(("", key))
            continue
        parts: list[str] = []
        cur = ""
        for line in text.split("\n"):
            line = line[:max_chars]
            if cur and len(cur) + len(line) + 1 > max_chars:
                parts.append(cur)
                cur = ""
            cur = f"{cur}\n{line}" if cur else line
        parts.append(cur)
        for i, part in enumerate(parts):
            pieces.append((part, key if i == len(parts) - 1 else None))
    chunks: list[tuple[str, list[str]]] = []
    text_acc = ""
    keys: list[str] = []
    for part, done_key in pieces:
        if text_acc and part and len(text_acc) + len(part) + 2 > max_chars:
            chunks.append((text_acc, keys))
            text_acc, keys = "", []
        if part:
            text_acc = f"{text_acc}\n\n{part}" if text_acc else part
        if done_key is not None:
            keys.append(done_key)
    if text_acc or keys:
        chunks.append((text_acc, keys))
    return chunks


def build_distill_prompt(
    turns: list[dict[str, Any]] | None = None,
    *,
    known: list[str],
    max_chars: int = 24000,
    transcript: str | None = None,
    entities: list[str] | None = None,
) -> str:
    """Prompt asking the model to extract durable team knowledge from chats.
    Pass a pre-chunked ``transcript`` (see :func:`chunk_transcripts`), or
    ``turns`` (rendered, keeping the last ``max_chars``). ``known`` are existing
    fact texts, so it doesn't re-propose them."""
    if transcript is None:
        transcript = render_turns(turns or [])[-max_chars:]
    known_block = "\n".join(f"- {k}" for k in known[:80]) or "(none yet)"
    entity_block = ", ".join((entities or [])[:300]) or "(none listed)"
    kinds = ", ".join(FACT_KINDS)
    types = ", ".join(ENTITY_TYPES)
    return (
        "You maintain a team knowledge wiki for an operations console. Read the "
        "recent conversations below and extract durable facts worth sharing with "
        "the rest of the team: where files and logs live on which hosts, what team "
        "jargon means, which tools go together, discovered facts about hosts / "
        "groups / profiles, knock-on effects of changes, and how the team usually "
        "does things.\n\n"
        "Rules:\n"
        "- Only facts that will still be true next week. No one-off results, no "
        "opinions, no secrets, passwords, tokens or personal data.\n"
        "- One or two sentences each, specific (name hosts, paths, runnables).\n"
        "- Skip anything already in the known list.\n"
        f"- kind is one of: {kinds}.\n"
        f"- about lists the entities as type:name, type one of: {types}.\n"
        "- When a fact is about one of the fleet's existing entities below, use "
        "that exact type:name (a host group is group:, not term:).\n"
        "- At most 12 facts. Fewer is fine; none is fine.\n\n"
        "Reply with ONLY a JSON array, e.g.\n"
        '[{"kind": "location", "about": ["host:web-01", "app:orders"], '
        '"text": "orders logs are in /var/log/orders/app.log on web-01"}]\n\n'
        f"Existing entities: {entity_block}\n\n"
        f"Known facts:\n{known_block}\n\nConversations:\n{transcript}"
    )


def parse_distill(text: str) -> list[dict[str, Any]]:
    """Pull the JSON array of candidate facts out of a model reply (tolerates
    surrounding prose / a fenced block). Invalid entries are dropped."""
    import json

    s = text or ""
    start, end = s.find("["), s.rfind("]")
    if start < 0 or end <= start:
        return []
    try:
        data = json.loads(s[start : end + 1])
    except ValueError:
        return []
    out = []
    for d in data if isinstance(data, list) else []:
        if not isinstance(d, dict):
            continue
        about = d.get("about")
        if isinstance(about, str):
            about = [about]
        if not isinstance(about, list) or not str(d.get("text") or "").strip():
            continue
        out.append(
            {
                "kind": str(d.get("kind") or "note"),
                "about": about,
                "text": str(d["text"]),
            }
        )
    return out[:20]
