"""
knowledge.py — the team knowledge wiki's local store, index and mechanical capture.

The agent's one fact store (it replaced the older ``remember`` / ``search_memory``
memory in 0.332.0 — see :func:`memory_to_facts`): **structured, shareable** facts
*about* named entities (hosts, groups, profiles, runnables, files, team jargon, …)
that link together into a graph and render as one wiki page per entity. A few facts
can be **pinned** (``state.toml``, machine-local) so they fold into every chat's
system prompt (:meth:`KnowledgeStore.header`). Design note:
``docs/design/console-knowledge-wiki.md``.

Files are the source of truth (TOML ``[[fact]]`` collections, diffable and, later,
pushable by Memory Sync); a SQLite index under the same directory is a derived
cache rebuilt whenever a source file changes. Layout under ``knowledge_dir()``::

    facts.toml     approved facts authored on this console (this operator's lane)
    inbox.toml     proposed facts awaiting the operator's review (never shared)
    observed.toml  mechanical observations, regenerated by ``capture`` (usage
                   patterns mined from run history — no AI involved)
    team/*.toml    facts pulled from the team wiki (Memory Sync; read-only here)
    state.toml     machine-local bookkeeping: capture range, distilled chats,
                   pinned fact ids (never shared)
    index.sqlite   derived search/graph cache — safe to delete

A fact::

    [[fact]]
    id = "k_3f9a1c0b2d"         # hash of kind + subjects + text, so the same fact
                                # proposed twice (or by two consoles) dedupes
    kind = "location"
    about = ["host:web-01", "runnable:tail-log"]
    text = "orders-svc logs live in /var/log/orders/app.log"
    status = "approved"         # approved | pending | observed | retired
    source = "agent"            # agent | mcp | operator | distill | capture | trigger:<name>
    author = "jason@desk-01"
    evidence = ["run:abc123"]    # ids only, never transcript text
    first_seen = "2026-10-04"
    last_confirmed = "2026-10-04"
    confirmations = 1

Everything here is stdlib (``sqlite3``; FTS5 when the build has it, a token-overlap
fallback otherwise) and pure apart from the file/index I/O, so it unit-tests on any
OS. The bridge (``bridge_knowledge.py``) owns when to read and write.
"""

