"""
stubgen.py — generate a self-contained stub that types ``parse()`` per runnable.

``runspec stubs`` scans the installed venv (the same discovery ``runspec local``
uses) and writes ``typings/runspec/__init__.pyi`` at the project root. Each
runnable becomes a standalone *view* class whose args are typed ``Arg[T]``, and
``parse()`` gains a ``@overload`` per runnable so ``args = parse("demo")`` is
precisely typed with no annotation or cast at the call site.

The view classes deliberately do **not** carry the dynamic-arg ``__getattr__``
(which returns ``Any``): they expose ``RunSpec``'s stable metadata surface via
the ``_RunSpecView`` base but nothing else, so a typo or an arg you haven't
regenerated for is a hard "no attribute" error rather than a silent ``Any``.

The stub is **self-contained**: ``Arg``/``Group``/``RunSpec`` are emitted into
the file itself (introspected from the real classes so they don't drift). It
cannot re-export from ``runspec.models`` etc., because once
``typings/runspec/__init__.pyi`` shadows the package a type checker roots
``runspec`` at ``typings/`` and can no longer find the real submodules.

Everything here is pure text generation — no filesystem side effects — so the
CLI (``cli.cmd_stubs``) owns reading/writing and this module stays testable.
"""

from __future__ import annotations

import dataclasses
import re
from typing import Any

from runspec.inference import infer_script
from runspec.models import _PYTHON_TYPE_NAMES, Arg, Group

_HEADER = """\
# Generated by `runspec stubs` — DO NOT EDIT.
# Regenerate after changing any runspec.toml:  runspec stubs
from pathlib import Path
from types import SimpleNamespace
from typing import Any, Generic, Literal, TypeVar, overload

_T = TypeVar("_T")
__version__: str
"""

# RunSpec's stable public surface (properties + lookup helpers), shared by the
# typed views and by RunSpec itself. test_stubgen guards it against drift.
_VIEW_BASE = '''\
class _RunSpecView:
    """RunSpec's stable public surface, minus the dynamic-arg ``__getattr__``.

    A typo or an arg not yet in this stub is a clear ``attr-defined`` error here,
    not a silent ``Any``. Regenerate with ``runspec stubs`` after editing a toml.
    """
    @property
    def runspec_runnable(self) -> str: ...
    @property
    def runspec_source(self) -> Path: ...
    @property
    def runspec_prefix(self) -> Path: ...
    @property
    def runspec_autonomy(self) -> str: ...
    @property
    def runspec_agent(self) -> bool: ...
    @property
    def runspec_spec(self) -> dict[str, Any]: ...
    @property
    def runspec_groups(self) -> list[Group]: ...
    @property
    def runspec_discoverable(self) -> list[str]: ...
    @property
    def runspec_command(self) -> str | None: ...
    @property
    def runspec_command_path(self) -> list[str]: ...
    def get(self, name: str, default: Any = ...) -> Arg[Any]: ...
    def get_runspec_env(self) -> SimpleNamespace: ...
    def __contains__(self, name: str) -> bool: ...'''

# RunSpec as the fallback parse() return: the metadata surface plus the
# dynamic-arg __getattr__ (Any), so generic `parse()` / `parse(var)` still works.
_RUNSPEC = """\
class RunSpec(_RunSpecView):
    def __getattr__(self, name: str) -> Any: ..."""


def _render_dataclass(cls: type, *, generic: bool = False, extra: str = "") -> str:
    """Emit a dataclass as a stub class from its real fields (so it can't drift).

    Field annotations are read as source strings (the modules use
    ``from __future__ import annotations``), so e.g. ``str | None`` round-trips.
    """
    base = "(Generic[_T])" if generic else ""
    lines = [f"class {cls.__name__}{base}:"]
    for f in dataclasses.fields(cls):
        if f.name.startswith("_"):
            continue  # internal storage (e.g. RunSpec._args) — not public API
        ann = "_T" if f.name == "value" else str(f.type)
        lines.append(f"    {f.name}: {ann}")
    if extra:
        lines.append(extra)
    return "\n".join(lines)


def _py_type(arg: dict[str, Any]) -> str:
    """Python type repr for an arg's ``.value`` — e.g. ``int``, ``list[str]``,
    ``Literal['json', 'yaml']``. Mirrors ``Arg.python_type`` but renders a
    ``choice`` arg's ``options`` as a precise ``Literal``."""
    item_type = arg.get("type", "str")
    options = arg.get("options")
    if options:
        base = "Literal[" + ", ".join(repr(o) for o in options) + "]"
    elif item_type == "rest":
        return "list[str]"
    else:
        base = _PYTHON_TYPE_NAMES.get(item_type, "str")
    if arg.get("multiple") and item_type != "rest":
        return f"list[{base}]"
    return base


def _view_name(runnable: str) -> str:
    """``demo`` → ``_DemoArgs``; ``my-tool`` → ``_MyToolArgs``."""
    parts = [p for p in re.split(r"[^0-9a-zA-Z]+", runnable) if p]
    camel = "".join(p[:1].upper() + p[1:] for p in parts) or "Runnable"
    return f"_{camel}Args"


def _attr(name: str) -> str:
    """Arg name as a Python identifier — hyphens to underscores (matches access)."""
    return name.replace("-", "_")


def collect_args(script: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """All args for a runnable as the *superset* across its subcommand tree.

    A subcommand changes the effective arg set at runtime, but statically we
    can't know which one is active, so the view lists every arg across all
    command paths. Presence-dependent args are read with ``args.get(...)`` /
    ``name in args`` (the documented idiom). First declaration of a name wins.
    """
    collected: dict[str, dict[str, Any]] = {}

    def walk(node: dict[str, Any]) -> None:
        for name, arg in node.get("args", {}).items():
            collected.setdefault(name, arg)
        for command in node.get("commands", {}).values():
            walk(command)

    walk(script)
    return collected


def render_view(runnable: str, args: dict[str, dict[str, Any]]) -> str:
    """One typed view class for a runnable."""
    lines = [f"class {_view_name(runnable)}(_RunSpecView):"]
    if args:
        lines += [f"    {_attr(name)}: Arg[{_py_type(arg)}]" for name, arg in args.items()]
    else:
        lines.append("    pass")
    return "\n".join(lines)


def render_overloads(runnables: list[str]) -> str:
    """The ``parse()`` overloads: a literal-keyed one per runnable, then the
    broad fallback to ``RunSpec`` for a non-literal/unknown name.

    Each literal overload overlaps the fallback with a narrower return type —
    the intended dispatch. mypy flags this on the *specific* overload's line, so
    the suppression goes there, not on the fallback.
    """
    sig = "argv: list[str] | None = ..., config_path: Path | None = ..."
    ignore = "  # type: ignore[overload-overlap]"
    out: list[str] = []
    for name in runnables:
        out.append("@overload")
        out.append(f'def parse(script_name: Literal["{name}"], {sig}) -> {_view_name(name)}: ...{ignore}')
    out.append("@overload")
    out.append(f"def parse(script_name: str | None = ..., {sig}) -> RunSpec: ...")
    out.append("")
    out.append("def load_spec(script_name: str | None = ..., config_path: Path | None = ...) -> RunSpec: ...")
    out.append("def register_type(name: str, coercer: Any) -> None: ...")
    return "\n".join(out)


def _prelude() -> list[str]:
    """Shared top of every generated stub: header + self-contained Arg/Group/
    RunSpec/_RunSpecView, so the file never re-exports from shadowed submodules."""
    return [
        _HEADER,
        _render_dataclass(Group),
        _render_dataclass(Arg, generic=True, extra="    @property\n    def python_type(self) -> str: ..."),
        _VIEW_BASE,
        _RUNSPEC,
    ]


def render_stub(specs: dict[str, dict[str, dict[str, Any]]]) -> str:
    """Full ``typings/runspec/__init__.pyi`` text.

    ``specs`` maps runnable name → its collected args ({arg name → arg dict}).
    Pure: identical input always yields byte-identical output (so ``--check``
    diffs are stable). Runnables are emitted in sorted order.
    """
    names = sorted(specs)
    blocks = _prelude()
    blocks += [render_view(name, specs[name]) for name in names]
    blocks.append(render_overloads(names))
    return "\n\n\n".join(blocks) + "\n"


# Placeholder name surfaced in the editor before `runspec stubs` has run — the
# type's name *is* the message.
_SENTINEL = '''\
class _StubsNotGenerated(_RunSpecView):
    """Run `runspec stubs` to enable typed, per-runnable arguments.

    Until then arg access (e.g. ``args.workers``) is a clear "no attribute"
    error rather than a silent ``Any``. Metadata (``runspec_*``, ``get``,
    ``in``) still works.
    """

@overload
def parse(script_name: Literal[None] = ..., argv: list[str] | None = ..., config_path: Path | None = ...) -> RunSpec: ...
@overload
def parse(script_name: str = ..., argv: list[str] | None = ..., config_path: Path | None = ...) -> _StubsNotGenerated: ...
def load_spec(script_name: str | None = ..., config_path: Path | None = ...) -> RunSpec: ...
def register_type(name: str, coercer: Any) -> None: ...'''


def render_sentinel_stub() -> str:
    """Placeholder stub written by ``runspec init`` before real generation.

    ``parse("<name>")`` is typed ``_StubsNotGenerated`` — metadata works, but
    touching an arg flags "run ``runspec stubs``". A bare ``parse()`` still
    yields ``RunSpec`` (the generic fallback). Replaced by the real stub on the
    first ``runspec stubs`` / ``runspec local``."""
    return "\n\n\n".join([*_prelude(), _SENTINEL]) + "\n"


def specs_from_discovered(discovered: list[dict[str, Any]]) -> dict[str, dict[str, dict[str, Any]]]:
    """Turn ``cli._discover_installed()`` items into ``render_stub`` input.

    Runs inference (so inferred types are reflected) and collects the subcommand
    superset. Duplicate runnable names across packages: first wins (overloads
    must key on a unique literal)."""
    specs: dict[str, dict[str, dict[str, Any]]] = {}
    for item in discovered:
        name = item["runnable"]
        if name in specs:
            continue
        autonomy = item.get("config_autonomy") or "confirm"
        inferred = infer_script(item["spec"], autonomy)
        specs[name] = collect_args(inferred)
    return specs
